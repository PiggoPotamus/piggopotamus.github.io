def decode_varints(byte_values: Sequence[int], expected: int, progress: Optional[Callable[[int], None]] = None) -> List[int]:
    data = [(b + 256) % 256 for b in byte_values]
    out: List[int] = []
    i = 0
    next_progress = 10
    if len(data) == expected and (not expected or max(data) < 0x80):
        if progress:
            progress(100)
        return list(data)
    while i < len(data) and len(out) < expected:
        value = 0
        shift = 0
        for _ in range(5):
            if i >= len(data):
                raise NBTError("Truncated varint in block data")
            b = data[i]
            i += 1
            value |= (b & 0x7F) << shift
            if (b & 0x80) == 0:
                out.append(value)
                if progress and expected > 0 and len(out) * 100 >= expected * next_progress:
                    progress(min(100, next_progress))
                    next_progress += 10
                break
            shift += 7
        else:
            raise NBTError("Varint exceeds 5 bytes")
    if progress and next_progress <= 100 and len(out) == expected:
        progress(100)
    if len(out) != expected:
        raise NBTError(f"Block data decoded to {len(out)} entries; expected {expected}")
    return out


def parse_palette(v: NBTValue, label: str) -> Dict[int, str]:
    d = compound(v, label)
    out: Dict[int, str] = {}
    for state, idx_tag in d.items():
        idx = int_value(idx_tag, f"{label}.{state}")
        if idx in out:
            raise NBTError(f"Duplicate palette index {idx}")
        out[idx] = state
    return out


def normalize_block_entity(raw: NBTValue, version: int) -> BlockEntity:
    d = compound(raw, "BlockEntity")
    pos = numeric_list(d.get("Pos"), "BlockEntity.Pos")
    if len(pos) != 3:
        raise NBTError("BlockEntity.Pos must contain exactly 3 integers")
    entity_id = string_value(d.get("Id") or d.get("id"), "BlockEntity.Id")

    if version >= 3 and d.get("Data") is not None:
        data_tag = d["Data"]
        if data_tag.tag != TAG_COMPOUND:
            raise NBTError("v3 BlockEntity.Data must be a compound")
        data_map = dict(data_tag.value)
    else:
        data_map = {k: v for k, v in d.items() if k not in {"Pos", "Id", "id"}}

    for k in ("x", "y", "z", "Pos", "Id", "id"):
        data_map.pop(k, None)

    return BlockEntity((pos[0], pos[1], pos[2]), entity_id, NBTValue(TAG_COMPOUND, data_map))


def load_schematic(path: str, progress: Optional[Callable[[str], None]] = None) -> Schematic:
    if progress:
        progress("Reading compressed NBT...")
    try:
        with gzip.open(path, "rb") as f:
            raw = f.read()
    except OSError as e:
        raise NBTError(f"Could not read gzip-compressed schematic: {e}") from e

    if progress:
        progress(f"Parsing {len(raw):,} bytes of decompressed NBT...")
    root_name, root_tag = NBTReader(raw).read_root()
    root = compound(root_tag, "NBT root")

    if "Schematic" in root and root["Schematic"].tag == TAG_COMPOUND:
        s = compound(root["Schematic"], "Schematic")
    else:
        s = root

    if 'Regions' in s:
        from schematic_formats import load_litematic
        return load_litematic(s, progress)
    if 'Blocks' in s and s['Blocks'].tag == TAG_BYTE_ARRAY and 'Data' in s:
        from schematic_formats import load_legacy
        return load_legacy(s, progress)
    version = int_value(s.get("Version"), "Version")
    if version not in (1, 2, 3):
        raise NBTError(f"Unsupported Sponge schematic Version {version}; supported: 1, 2, 3")
    data_version = int_value(s.get("DataVersion"), "DataVersion") if s.get("DataVersion") else -1
    width = int_value(s.get("Width"), "Width")
    height = int_value(s.get("Height"), "Height")
    length = int_value(s.get("Length"), "Length")
    if min(width, height, length) <= 0:
        raise NBTError(f"Invalid schematic dimensions {width}x{height}x{length}")


    volume = width * height * length
    if version >= 3:
        blocks_container_tag = s.get("Blocks")
        if blocks_container_tag is None:
            raise NBTError("v3 schematic has no Blocks compound")
        bc = compound(blocks_container_tag, "Blocks")
        palette_tag = bc.get("Palette")
        data_tag = bc.get("Data")
        be_tag = bc.get("BlockEntities")
    else:
        palette_tag = s.get("Palette")
        data_tag = s.get("BlockData")
        be_tag = s.get("BlockEntities") or s.get("TileEntities")

    if palette_tag is None or data_tag is None:
        raise NBTError("Schematic is missing block Palette or block Data")
    if data_tag.tag != TAG_BYTE_ARRAY:
        raise NBTError("Block data must be stored as an NBT byte array of varints")

    palette = parse_palette(palette_tag, "Palette")
    if progress:
        progress(f"Decoding {volume:,} block palette indices...")
    indices = decode_varints(
        data_tag.value, volume,
        progress=(lambda pct: progress(f"Block-data decode: {pct}%")) if progress else None
    )
    if progress:
        progress(f"Expanding {volume:,} palette indices to block states...")
    try:
        blocks = [palette[i] for i in indices]
    except KeyError as e:
        raise NBTError(f"Block data refers to missing palette index {e.args[0]}") from e

    block_entities: List[BlockEntity] = []
    if be_tag is not None:
        if be_tag.tag != TAG_LIST:
            raise NBTError("BlockEntities must be an NBT list")
        _, vals = be_tag.value
        for item in vals:
            block_entities.append(normalize_block_entity(item, version))

    entities_tag = s.get("Entities")
    entity_count = 0
    if entities_tag is not None and entities_tag.tag == TAG_LIST:
        entity_count = len(entities_tag.value[1])

    metadata: Dict[str, NBTValue] = {}
    if s.get("Metadata") is not None and s["Metadata"].tag == TAG_COMPOUND:
        metadata = dict(s["Metadata"].value)
    for meta_key in ("Name", "Description", "Author", "SchematicAuthor", "Creator"):
        if meta_key not in metadata and s.get(meta_key) is not None:
            metadata[meta_key] = s[meta_key]

    return Schematic(version, data_version, width, height, length, blocks,
                     block_entities, entity_count, metadata)


def _nbt_plain_text(v: Optional[NBTValue]) -> Optional[str]:
    if v is None:
        return None
    if v.tag == TAG_STRING:
        text = str(v.value).strip()
        return text or None
    return None


def schematic_metadata_text(schem: Schematic, *keys: str) -> Optional[str]:
    """Find a simple string metadata field, case/underscore/space-insensitively."""
    wanted = {re.sub(r"[ _-]+", "", k).lower() for k in keys}

    def search_map(values: Dict[str, NBTValue]) -> Optional[str]:
        for key, value in values.items():
            if re.sub(r"[ _-]+", "", key).lower() in wanted:
                text = _nbt_plain_text(value)
                if text:
                    return text
        for value in values.values():
            if value.tag == TAG_COMPOUND:
                found = search_map(value.value)
                if found:
                    return found
        return None

    return search_map(schem.metadata)


def schematic_author(schem: Schematic) -> Optional[str]:
    return schematic_metadata_text(schem, "Author", "SchematicAuthor", "Creator")



@dataclass(frozen=True)
class Cuboid:
    state: str
    x1: int
    y1: int
    z1: int
    x2: int
    y2: int
    z2: int

    @property
    def volume(self) -> int:
        return (self.x2 - self.x1 + 1) * (self.y2 - self.y1 + 1) * (self.z2 - self.z1 + 1)

    def bounds(self) -> Tuple[Tuple[int, int, int], Tuple[int, int, int]]:
        return (self.x1, self.y1, self.z1), (self.x2, self.y2, self.z2)


def coord_to_index(coord: Sequence[int], dims: Sequence[int]) -> int:
    x, y, z = coord
    w, h, l = dims
    return x + z * w + y * w * l


def partition_order(blocks: Sequence[str], dims: Tuple[int, int, int],
                    order: Tuple[int, int, int], include_air: bool,
                    progress: Optional[Callable[[int], None]] = None) -> List[Cuboid]:
    """Partition selected voxels into cuboids using a run -> rectangle -> cuboid merge.

    Trying all six axis orders later avoids a single orientation bias while retaining
    O(N)ish behavior per orientation rather than using an expensive NP-ish global cover.
    """
    a, b, c = order
    da, db, dc = dims[a], dims[b], dims[c]

    runs_by_c: List[List[Tuple[str, int, int, int]]] = [[] for _ in range(dc)]
    coord = [0, 0, 0]
    reported_progress = 0
    for cv in range(dc):
        coord[c] = cv
        for bv in range(db):
            coord[b] = bv
            av = 0
            while av < da:
                coord[a] = av
                state = blocks[coord_to_index(coord, dims)]
                if state == "__unselected__" or ((not include_air) and state in AIR_STATES):
                    av += 1
                    continue
                start = av
                av += 1
                while av < da:
                    coord[a] = av
                    if blocks[coord_to_index(coord, dims)] != state:
                        break
                    av += 1
                runs_by_c[cv].append((state, start, av - 1, bv))
        if progress and dc > 0:
            pct = ((cv + 1) * 100) // dc
            checkpoint = min(100, (pct // 25) * 25)
            if checkpoint > reported_progress:
                reported_progress = checkpoint
                progress(checkpoint)

    rects_by_c: List[List[Tuple[str, int, int, int, int]]] = [[] for _ in range(dc)]
    for cv, runs in enumerate(runs_by_c):
        groups: Dict[Tuple[str, int, int], List[int]] = {}
        for state, a1, a2, bv in runs:
            groups.setdefault((state, a1, a2), []).append(bv)
        rects: List[Tuple[str, int, int, int, int]] = []
        for (state, a1, a2), bvals in groups.items():
            bvals.sort()
            b1 = prev = bvals[0]
            for bv in bvals[1:]:
                if bv == prev + 1:
                    prev = bv
                else:
                    rects.append((state, a1, a2, b1, prev))
                    b1 = prev = bv
            rects.append((state, a1, a2, b1, prev))
        rects_by_c[cv] = rects

    groups3: Dict[Tuple[str, int, int, int, int], List[int]] = {}
    for cv, rects in enumerate(rects_by_c):
        for state, a1, a2, b1, b2 in rects:
            groups3.setdefault((state, a1, a2, b1, b2), []).append(cv)

    result: List[Cuboid] = []
    for (state, a1, a2, b1, b2), cvals in groups3.items():
        cvals.sort()
        c1 = prev = cvals[0]
        spans: List[Tuple[int, int]] = []
        for cv in cvals[1:]:
            if cv == prev + 1:
                prev = cv
            else:
                spans.append((c1, prev))
                c1 = prev = cv
        spans.append((c1, prev))

        for c1, c2 in spans:
            lo = [0, 0, 0]
            hi = [0, 0, 0]
            lo[a], hi[a] = a1, a2
            lo[b], hi[b] = b1, b2
            lo[c], hi[c] = c1, c2
            result.append(Cuboid(state, lo[0], lo[1], lo[2], hi[0], hi[1], hi[2]))
    return result


def _split_count_candidates(d: int) -> List[int]:
    """Counts that can be optimal for ceil(d / count), in O(sqrt(d)) values."""
    if d <= 1:
        return [1]
    r = math.isqrt(d)
    vals = set(range(1, r + 1))
    for chunk_size in range(1, r + 1):
        vals.add((d + chunk_size - 1) // chunk_size)
    vals.add(d)
    return sorted(v for v in vals if 1 <= v <= d)


def _segments(lo: int, length: int, count: int) -> List[Tuple[int, int]]:
    """Split an integer extent into count near-equal inclusive segments."""
    base, rem = divmod(length, count)
    out = []
    cur = lo
    for i in range(count):
        size = base + (1 if i < rem else 0)
        out.append((cur, cur + size - 1))
        cur += size
    return out


def split_cuboid(c: Cuboid, max_volume: int) -> List[Cuboid]:
    """Split a cuboid into a near-minimal number of legal /fill cuboids.

    The theoretical lower bound is ceil(volume / max_volume). We search the
    O(sqrt(d)) meaningful split counts on two axes and solve the third axis
    directly, trying all choices of direct axis. This avoids the common waste
    of simple slab-only splitting (for example, a 100^3 cube at 32768 blocks
    can be split into 32 fills instead of 34 slabs).
    """
    if max_volume <= 0 or c.volume <= max_volume:
        return [c]

    lengths = [c.x2 - c.x1 + 1, c.y2 - c.y1 + 1, c.z2 - c.z1 + 1]
    candidates = [_split_count_candidates(d) for d in lengths]
    best_counts: Optional[Tuple[int, int, int]] = None
    best_metric: Optional[Tuple[int, int, Tuple[int, int, int]]] = None

    for direct in range(3):
        others = [i for i in range(3) if i != direct]
        a, b = others
        for na in candidates[a]:
            sa = (lengths[a] + na - 1) // na
            for nb in candidates[b]:
                sb = (lengths[b] + nb - 1) // nb
                cross = sa * sb
                if cross > max_volume:
                    continue
                max_sd = max_volume // cross
                nd = (lengths[direct] + max_sd - 1) // max_sd
                nd = max(1, min(lengths[direct], nd))
                sd = (lengths[direct] + nd - 1) // nd
                if sa * sb * sd > max_volume:
                    while nd < lengths[direct] and sa * sb * sd > max_volume:
                        nd += 1
                        sd = (lengths[direct] + nd - 1) // nd
                    if sa * sb * sd > max_volume:
                        continue
                counts = [1, 1, 1]
                counts[a], counts[b], counts[direct] = na, nb, nd
                count_tuple = (counts[0], counts[1], counts[2])
                pieces = counts[0] * counts[1] * counts[2]
                split_axes = sum(1 for n in counts if n > 1)
                metric = (pieces, split_axes, count_tuple)
                if best_metric is None or metric < best_metric:
                    best_metric = metric
                    best_counts = count_tuple

    if best_counts is None:
        best_counts = tuple(lengths)  # type: ignore[assignment]

    xs = _segments(c.x1, lengths[0], best_counts[0])
    ys = _segments(c.y1, lengths[1], best_counts[1])
    zs = _segments(c.z1, lengths[2], best_counts[2])
    out = [
        Cuboid(c.state, x1, y1, z1, x2, y2, z2)
        for (y1, y2) in ys
        for (z1, z2) in zs
        for (x1, x2) in xs
    ]
    return out


def optimize(schem: Schematic, include_air: bool, max_fill_volume: int, progress: Optional[Callable[[str], None]] = None) -> Tuple[List[Cuboid], Tuple[int, int, int]]:
    dims = (schem.width, schem.height, schem.length)
    best: Optional[List[Cuboid]] = None
    best_order: Optional[Tuple[int, int, int]] = None
    best_metric = None

    orders = list(itertools.permutations((0, 1, 2)))
    for order_index, order in enumerate(orders, 1):
        order_name = "".join("XYZ"[i] for i in order)
        if progress:
            progress(f"Optimizer {order_index}/6 ({order_name}): scanning blocks...")
        raw = partition_order(
            schem.blocks, dims, order, include_air,
            progress=(lambda pct, oi=order_index, on=order_name: progress(f"Optimizer {oi}/6 ({on}): {pct}% scanned")) if progress else None
        )
        split: List[Cuboid] = []
        for c in raw:
            split.extend(split_cuboid(c, max_fill_volume))
        singles = sum(1 for c in split if c.volume == 1)
        metric = (len(split), singles, order)
        if progress:
            progress(f"Optimizer {order_index}/6 ({order_name}): {len(split):,} fill regions")
        if best_metric is None or metric < best_metric:
            best_metric = metric
            best = split
            best_order = order

    assert best is not None and best_order is not None
    best.sort(key=lambda c: (-c.volume, c.state, c.y1, c.z1, c.x1, c.y2, c.z2, c.x2))
    return best, best_order


