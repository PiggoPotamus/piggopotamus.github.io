FillGroup = Tuple[str, List[str]]


def _group_fill_phase(fill_entries: Sequence[str]) -> List[FillGroup]:
    """Group a reorder-safe phase by full block argument, preserving first-seen order."""
    grouped: Dict[str, List[str]] = {}
    for entry in fill_entries:
        coords, block = _split_fill_entry(entry)
        grouped.setdefault(block, []).append(coords)
    return [(block, coords) for block, coords in grouped.items()]


def group_fill_entries(fill_entries: Sequence[str], air_clear_fills: int,
                       non_air_fills: int) -> List[FillGroup]:
    """Compact F by storing each block argument once per safe placement phase.

    Air pre-clear, ordinary non-overlapping cuboids, and block-entity restore fills
    are kept as separate phases so grouping never moves a restore ahead of the base
    placement it is supposed to overwrite. Within each phase, fills do not overlap,
    so grouping by block argument is order-safe under `fill ... strict`.
    """
    a = air_clear_fills
    b = a + non_air_fills
    if a < 0 or non_air_fills < 0 or b > len(fill_entries):
        raise ValueError("invalid fill phase counts while grouping payload")
    phases = (fill_entries[:a], fill_entries[a:b], fill_entries[b:])
    groups: List[FillGroup] = []
    for phase in phases:
        if phase:
            groups.extend(_group_fill_phase(phase))
    return groups


def _group_open_bytes(block: str) -> int:
    return len(("[" + quote_output_entry(block) + "\n").encode("utf-8"))


def _group_coord_bytes(coords: str) -> int:
    return len((quote_output_entry(coords) + "\n").encode("utf-8"))


def _group_close_bytes() -> int:
    return len("],\n".encode("utf-8"))


def render_fill_group_lines(fill_groups: Sequence[FillGroup]) -> List[str]:
    lines: List[str] = []
    for block, coords_list in fill_groups:
        lines.append("[" + quote_output_entry(block))
        lines.extend(quote_output_entry(coords) for coords in coords_list)
        lines.append("],")
    return lines


def fill_group_payload_size(fill_groups: Sequence[FillGroup]) -> int:
    close = _group_close_bytes()
    total = 0
    for block, coords_list in fill_groups:
        total += _group_open_bytes(block) + close
        total += sum(_group_coord_bytes(coords) for coords in coords_list)
    return total


def fill_group_command_count(fill_groups: Sequence[FillGroup]) -> int:
    return sum(len(coords) for _, coords in fill_groups)


def split_fill_groups(fill_groups: Sequence[FillGroup],
                      limit_bytes: int = ITEM_FILL_PAYLOAD_LIMIT_BYTES) -> List[List[FillGroup]]:
    """Split grouped F payload into contiguous item parts under the byte limit.

    A block group may be split across item files; its block argument is then repeated
    once at the start of each affected part. Coordinate order and group/phase order are
    preserved exactly.
    """
    if limit_bytes <= 0:
        raise ValueError("fill payload limit must be positive")

    parts: List[List[FillGroup]] = []
    current: List[FillGroup] = []
    current_bytes = 0
    close_bytes = _group_close_bytes()

    def flush() -> None:
        nonlocal current, current_bytes
        if current:
            parts.append(current)
            current = []
            current_bytes = 0

    for block, coords_list in fill_groups:
        open_bytes = _group_open_bytes(block)
        overhead = open_bytes + close_bytes
        if not coords_list:
            continue
        i = 0
        while i < len(coords_list):
            first_coord_bytes = _group_coord_bytes(coords_list[i])
            if overhead + first_coord_bytes > limit_bytes:
                raise ValueError(
                    f"one grouped fill entry for {block!r} needs {overhead + first_coord_bytes:,} UTF-8 bytes, "
                    f"larger than the {limit_bytes:,}-byte per-item fill-payload limit"
                )

            if current_bytes + overhead + first_coord_bytes > limit_bytes:
                flush()

            chunk: List[str] = []
            current.append((block, chunk))
            current_bytes += overhead

            while i < len(coords_list):
                cb = _group_coord_bytes(coords_list[i])
                if current_bytes + cb > limit_bytes:
                    break
                chunk.append(coords_list[i])
                current_bytes += cb
                i += 1

            if not chunk:
                raise AssertionError("group splitter failed to place a coordinate")
            if i < len(coords_list):
                flush()

    flush()
    if not parts:
        parts.append([])
    return parts


def _part_output_path(output: str, part_index: int, part_count: int) -> str:
    if part_count <= 1:
        return output
    root, ext = os.path.splitext(output)
    return f"{root}_part{part_index}{ext}"


def render_payload_lines(payload: Dict[str, Any]) -> List[str]:
    """custom_data entries for one item: S (decoder setup commands), C (byte
    chunks), T (token table) and E (block-entity commands, run last)."""
    return [
        'S:' + schem_ops.snbt(payload['S']) + ',',
        'C:[' + ',\n'.join(schem_ops.snbt_bytes(c) for c in payload['C']) + '],',
        'T:' + schem_ops.snbt(payload['T']) + ',',
        'E:' + schem_ops.snbt(payload['E']) + ',',
    ]


def _minecart(command: str, tags: str = "") -> str:
    return '{id:"command_block_minecart",Command:"' + command + '"' + tags + '},'


CUSTOM = r'block ~ ~-1 ~ components.\\"minecraft:custom_data\\".'


def _loading_part(text: str, part: Dict[str, Any]) -> str:
    """Make a part of a multi-item build load into storage p2:p first.

    Its block runs a short minecart list that stores the part's chunks. Until
    every part has arrived it then removes itself; the part that completes the
    set switches its block to the full loader (kept as L), which gathers the
    chunks in order. So parts can be placed anywhere, in any order, and the
    build starts from the last one."""
    k, n, build = part["k"], part["n"], part["id"]
    has = r'p2:p {P:{id:\\"' + build + r'\\"}}'
    say = (r'{\\"color\\":\\"aqua\\",\\"text\\":\\"[Schematic] Loaded \\",\\"extra\\":['
           r'{\\"score\\":{\\"name\\":\\"#h\\",\\"objective\\":\\"p2l\\"}},'
           + rf'\\" of {n} parts. Place the rest, with the last one placed where you want the schematic. \\",'
           + r'{\\"text\\":\\"[Cancel]\\",\\"color\\":\\"red\\",\\"click_event\\":{\\"action\\":\\"run_command\\",'
           r'\\"command\\":\\"/data remove storage p2:p P\\"}}]}')
    dropped = (r'{\\"color\\":\\"yellow\\",\\"text\\":\\"[Schematic] Dropped the loaded parts of another schematic.\\"}')
    carts = [
        _minecart("gamerule command_block_output false", ',Tags:["p2.xx"]'),
        _minecart("scoreboard objectives add p2l dummy"),
        _minecart(f"execute if data storage p2:p P unless data storage {has} run tellraw @a[distance=..16] {dropped}"),
        _minecart(f"execute unless data storage {has} run data modify storage p2:p P set value " + r'{id:\\"' + build + r'\\",k:{}}'),
        _minecart(f"data modify storage p2:p P.k.p{k} set value 1b"),
        _minecart(f"data modify storage p2:p P.c{k} set from {CUSTOM}C"),
        _minecart(f"data modify storage p2:p P.e{k} set from {CUSTOM}E"),
        _minecart("execute store result score #h p2l run data get storage p2:p P.k"),
        _minecart(f"execute if score #h p2l matches ..{n - 1} run tellraw @a[distance=..16] {say}"),
        _minecart(f"execute if score #h p2l matches {n} run data modify block ~ ~-1 ~ Command set from {CUSTOM}L"),
        _minecart(f"execute if score #h p2l matches ..{n - 1} run data modify block ~ ~-1 ~ Command set value "
                  + r'\\"fill ~ ~ ~ ~ ~1 ~ air strict\\"'),
        _minecart("scoreboard objectives remove p2l"),
        _minecart("kill @e[type=command_block_minecart,distance=..3]"),
    ]
    carts[-1] = carts[-1].rstrip(",")
    start = "Command:'execute unless entity @e[type=command_block_minecart,dx=0,tag=p2.xx] if block ~ ~1 ~ activator_rail run summon item ~ ~0.7 ~ {Passengers:["
    if text.count(start) != 1:
        raise ValueError("item template is missing the loader command")
    text = text.replace(start, start + "\n" + "\n".join(carts) + "]}',\n\nL:'" + start[len("Command:'"):])
    gather = [_minecart("execute if data storage p2:p P run data modify storage p2:l C set value []"),
              _minecart("execute if data storage p2:p P run data modify storage p2:l E set value []")]
    for i in range(1, n + 1):
        gather.append(_minecart(f"data modify storage p2:l C append from storage p2:p P.c{i}[]"))
        gather.append(_minecart(f"data modify storage p2:l E append from storage p2:p P.e{i}[]"))
    for key, new in (("C", "\n".join(gather)), ("E", "")):
        line = _minecart(f"data modify storage p2:l {key} set from {CUSTOM}{key}") + "\n"
        if text.count(line) != 1:
            raise ValueError(f"item template is missing the {key} load")
        text = text.replace(line, new + ("\n" if new else ""))
    return text


def render_dynamic_item(template: str, schem: Schematic, payload: Dict[str, Any],
                        origin: Tuple[int, int, int], relative: bool,
                        name: str, description: str, author: str, include_credit: bool,
                        bounds_block: str, bounds_thickness: float) -> str:
    """Fill the PiggoPotamus loader template with this schematic.

    The payload (see render_payload_lines) replaces <PAYLOAD>; the executor
    ring replaces <EXECUTOR>. Large footprints are split into legal forceload
    rectangles and the cleanup chain is resized/routed automatically.
    """
    forceload_args = _forceload_arguments(schem, origin, relative)
    cleanup_lines, staging = _cleanup_minecart_lines(forceload_args, payload.get("restore", ()))
    placement_base = origin
    bounds_translation_base = placement_base if relative else (0, 0, 0)
    bounds_passengers, bounds_shared = _bounding_box_display_parts(
        schem, block=bounds_block, thickness=bounds_thickness, tag="p2.x",
        glow_color_override=16737792, translation_base=bounds_translation_base
    )
    bounds_root_uuid = "00014319-0001-4319-0000-58b900014319"
    bounds_root_nbt = (
        '{UUID:[I;82713,82713,22713,82713],Tags:["p2.x"],Passengers:['
        + ','.join(bounds_passengers) + ']}'
    )
    bounds_root_summon = 'summon block_display ~ ~ ~ ' + bounds_root_nbt
    bounds_root_summon_nested = _escape_nested_minecart_command(bounds_root_summon)
    bounds_merge = (
        f"execute as {bounds_root_uuid} on passengers "
        "run data merge entity @s " + bounds_shared
    )
    bounds_merge_nested = _escape_nested_minecart_command(bounds_merge)
    bounds_teleport_nested: Optional[str] = None
    if not relative:
        bx, by, bz = placement_base
        bounds_teleport = f"tp {bounds_root_uuid} {bx} {by} {bz}"
        bounds_teleport_nested = _escape_nested_minecart_command(bounds_teleport)

    lines = template.splitlines()
    out: List[str] = []
    template_has_max_mod_rule = (
        'gamerule max_block_modifications ' in template
        or 'gamerule minecraft:max_block_modifications ' in template
    )

    if lines.count("<PAYLOAD>") != 1 or lines.count("<EXECUTOR>") != 1:
        raise ValueError("item template is missing its <PAYLOAD> or <EXECUTOR> placeholder")

    in_cleanup = False
    saw_add = saw_bounds = saw_cleanup = False
    i = 0
    while i < len(lines):
        line = lines[i]

        if line == "<PAYLOAD>":
            out.extend(render_payload_lines(payload))
            i += 1
            continue
        if line == "<EXECUTOR>":
            out.extend('{id:"command_block_minecart",Command:"' + sb.replace("'", "\\'") + '"},'
                       for sb in schem_ops.executor_blocks())
            i += 1
            continue

        line = line.replace(
            "Command:'execute if block ~ ~1 ~ activator_rail run summon item",
            "Command:'execute unless entity @e[type=command_block_minecart,dx=0,tag=p2.xx] "
            "if block ~ ~1 ~ activator_rail run summon item"
        )

        if 'Command:"gamerule command_block_output false"' in line:
            if 'Tags:["p2.xx"]' not in line:
                line = re.sub(
                    r'(\{id:"command_block_minecart",Command:"gamerule command_block_output false")(\},?)',
                    r'\1,Tags:["p2.xx"]\2', line, count=1
                )
            out.append(line)
            if not template_has_max_mod_rule:
                out.append('{id:"command_block_minecart",Command:"gamerule max_block_modifications 9999999"},')
            i += 1
            continue

        if 'setblock 28800024 176 28800002 repeating_command_block' in line:
            in_cleanup = True
            saw_cleanup = True
            out.extend(cleanup_lines)
            i += 1
            continue
        if in_cleanup:
            if 'fill 28800018 176 28800002 ' in line and ' air strict' in line:
                in_cleanup = False
            i += 1
            continue

        if 'execute at 00014317-0001-4317-0000-58b700014317 run forceload add ' in line:
            if not saw_add:
                for arg in forceload_args:
                    out.append(
                        '{id:"command_block_minecart",Command:"execute at '
                        '00014317-0001-4317-0000-58b700014317 run forceload add ' + arg + '"},'
                    )
                if bounds_teleport_nested is not None:
                    out.append('{id:"command_block_minecart",Command:"' + bounds_teleport_nested + '"},')
                saw_add = True
            i += 1
            continue
        if 'summon text_display' in line and 'UUID:[I;82711,82711,22711,82711]' in line:
            marker = 'Passengers:['
            if marker in line:
                marker_at = line.index(marker)
                start_p = marker_at + len(marker)
                depth = 1
                j = start_p
                while j < len(line) and depth:
                    if line[j] == '[':
                        depth += 1
                    elif line[j] == ']':
                        depth -= 1
                    j += 1
                if depth:
                    raise ValueError("unterminated Passengers list in template text_display")
                cut = marker_at - 1 if marker_at > 0 and line[marker_at - 1] == ',' else marker_at
                line = line[:cut] + line[j:]
            if not relative:
                bx, by, bz = placement_base
                confirm = f"Confirm/Cancel placement at {bx} {by} {bz}"
                line = re.sub(
                    r'Confirm/Cancel placement(?: at -?\d+ -?\d+ -?\d+)?:',
                    confirm, line, count=1
                )
                line = line.replace('Confirm/Cancel placement:', confirm)
            out.append(line)
            out.append('{id:"command_block_minecart",Command:"' + bounds_root_summon_nested + '"},')
            out.append('{id:"command_block_minecart",Command:"' + bounds_merge_nested + '"},')
            saw_bounds = True
            i += 1
            continue

        if (('run summon block_display' in line or 'run summon marker' in line) and 'Passengers:' in line):
            i += 1
            continue
        if ('as @e[type=minecraft:block_display,dx=0] run data merge entity @s' in line
                or 'on passengers run data merge entity @s' in line):
            i += 1
            continue

        if ('setblock 28800023 185 28800002 chain_command_block' in line
                and 'kill @e[type=command_block_minecart,distance=..3]' in line):
            watcher_cmd = (
                'execute unless entity 00014317-0001-4317-0000-58b700014317 '
                'run data merge block 28800024 176 28800002 {auto:1b}'
            )
            watcher = (
                "{id:\"command_block_minecart\",Command:\"setblock 28800023 185 28800002 "
                "chain_command_block[facing=up]{auto:1b,Command:\\'" + watcher_cmd + "\\'}\"},"
            )
            out.append(watcher)
            line = line.replace('setblock 28800023 185 28800002',
                                'setblock 28800023 186 28800002', 1)

        if 'lore=[' in line and '],enchantment_glint_override' in line:
            start = line.index('lore=[') + len('lore=[')
            end = line.index('],enchantment_glint_override', start)
            desc_components = ['{"color":"gray","italic":false,"text":' + json.dumps(d, ensure_ascii=False) + '}'
                               for d in description.split("\n")]
            author_component = ('[{"color":"dark_gray","italic":false,"text":"Schem author: "},'
                                '{"color":"aqua","italic":false,"text":' + json.dumps(author, ensure_ascii=False) + '}]')
            lore_parts = [*desc_components, author_component]
            if not relative:
                bx, by, bz = placement_base
                origin_component = (
                    '[{"color":"dark_gray","italic":false,"text":"Origin: "},'
                    '{"color":"yellow","italic":false,"text":'
                    + json.dumps(f"{bx} {by} {bz}", ensure_ascii=False) + '}]'
                )
                lore_parts.append(origin_component)
            if include_credit:
                lore_parts.append('{"color":"red","italic":false,"text":' +
                                  json.dumps(VISIBLE_GENERATOR_CREDIT, ensure_ascii=False) + '}')
            line = line[:start] + ','.join(lore_parts) + line[end:]

        if 'custom_data={' in line and (
                'pg.schemloader' in line or 'GeneratedByPiggoSchemConverter:' in line
                or 'MadeByPiggo' in line or 'PiggoPotamus:1b' in line):
            line = re.sub(r'(?<![A-Za-z0-9_.-])MadeByPiggo:1b,?', '', line)
            line = re.sub(r'(?<![A-Za-z0-9_.-])author:"PiggoPotamus",?', '', line)
            line = re.sub(r'(?<![A-Za-z0-9_.-])PiggoPotamus:1b,?', '', line)
            line = line.replace('custom_data={,', 'custom_data={')
            while ',,' in line:
                line = line.replace(',,', ',')
            if 'GeneratedByPiggoSchemConverter:' not in line:
                marker = 'custom_data={'
                at = line.index(marker) + len(marker)
                entry = ('GeneratedByPiggoSchemConverter:' +
                         json.dumps(PERMANENT_GENERATOR_ATTRIBUTION, ensure_ascii=False) + ',')
                line = line[:at] + entry + line[at:]

        if 'Command:"fill 28800018 176 28800002 28800024 ' in line and ' 28800007 air strict"' in line:
            replacement = (
                f'fill {staging[0]} {staging[1]} {staging[2]} '
                f'{staging[3]} {staging[4]} {staging[5]} air strict'
            )
            line = re.sub(
                r'fill 28800018 176 28800002 28800024 -?\d+ 28800007 air strict',
                replacement, line, count=1
            )

        out.append(line)
        i += 1

    if in_cleanup:
        raise ValueError("item template cleanup section was not terminated as expected")
    if not saw_add:
        raise ValueError("item template is missing the schematic forceload-add placeholder")
    if not saw_bounds:
        raise ValueError("item template is missing the schematic block-display placeholder")
    if not saw_cleanup:
        raise ValueError("item template is missing the cleanup command-block chain")

    text = "\n".join(out)
    text = text.replace("<NAME>", _json_text_fragment(name))
    text = text.replace("<DESCRIPTION>", _json_text_fragment(description))
    if payload.get("part"):
        text = _loading_part(text, payload["part"])
    if not text.endswith("\n"):
        text += "\n"
    return text


CHUNK_BYTES = 1000  # bytes resolved per decoder pass: 400 cost about 4% more per tick, 2500 no less
ANCHOR = "00014317-0001-4317-0000-58b700014317"  # the confirmation text, at the loader
MULTI_HOW = ["Place each of the parts for the full schematic.", "Place the last one where you want the schematic."]
ENFORCE_ITEM_LIMIT = True


def build_print(schem: Schematic, include_air: bool, max_fill_volume: int,
                origin: Tuple[int, int, int], relative: bool, compact_states: bool,
                effort: str, block_entities: bool = True,
                progress: Optional[Callable[[str], None]] = None, empty_area: bool = False) -> Dict[str, Any]:
    """Plan the print (schem_ops.plan) and pack it: the decoder setup S, the
    token table T, the byte chunks and the block-entity commands E."""
    names: Dict[str, int] = {}
    ids: List[int] = []
    for b in schem.blocks:
        if b == "__unselected__":
            ids.append(schem_ops.FORBIDDEN)
        elif not include_air and b in AIR_STATES:
            ids.append(schem_ops.EMPTY if empty_area else schem_ops.FORBIDDEN)
        else:
            ids.append(names.setdefault(compact_block_state(b) if compact_states else b, len(names)))
    restore: List[str] = []
    restored = set()
    if relative:
        for dy in (0, 1):
            cell = (-origin[0], dy - origin[1], -origin[2])
            if not all(0 <= cell[i] < (schem.width, schem.height, schem.length)[i] for i in range(3)):
                continue
            i = schem.index(*cell)
            if ids[i] == schem_ops.EMPTY:  # not empty until the loader has gone
                ids[i] = names.setdefault("air", len(names))
            if ids[i] == schem_ops.FORBIDDEN:
                continue
            state = schem.blocks[i]
            if state in AIR_STATES:
                continue
            args = f"~ ~{dy or ''} ~ ~ ~{dy or ''} ~ " + (compact_block_state(state) if compact_states else state)
            be = next((e for e in schem.block_entities if e.pos == cell), None)
            if be is not None and block_entities:
                full = fill_args_for_block_entity(be, state, (-cell[0], dy - cell[1], -cell[2]), True, compact_states)
                if full is not None and "'" not in full:
                    args = full
            restored.add(cell)
            restore.append(f"execute at {ANCHOR} run fill {args} strict")
    grid = schem_ops.Grid(schem.width, schem.height, schem.length)
    target = schem_ops.Target(grid, ids, list(names))

    def estimate(commands: int) -> None:
        packed = commands * 7.5
        parts = max(math.ceil(packed / (schem_ops.NBT_QUOTA * schem_ops.QUOTA_SHARE - 70_000)) if ENFORCE_ITEM_LIMIT else 1,
                    math.ceil(packed * 4.2 / ITEM_FILL_PAYLOAD_LIMIT_BYTES))
        if parts > 1:
            print(f"NOTICE: This build will probably be split into about {parts} items.", file=sys.stderr, flush=True)

    ops, stats = schem_ops.plan(target, effort, max_fill_volume or 10 ** 9, progress, on_first=estimate)
    if relative:
        base, off = f"execute at {ANCHOR} ", origin
    else:
        base, off = "execute positioned %d %d %d " % origin, (0, 0, 0)
    enc = schem_ops.encode(ops, {i: n for n, i in names.items()}, off, base, CHUNK_BYTES)
    entity_commands: List[str] = []
    for be in schem.block_entities if block_entities else ():
        x, y, z = be.pos
        if not (0 <= x < schem.width and 0 <= y < schem.height and 0 <= z < schem.length):
            raise NBTError(f"Block entity {be.entity_id} has out-of-bounds Pos {be.pos}")
        if be.pos in restored:
            continue
        args = fill_args_for_block_entity(be, schem.block_at(x, y, z), origin, relative, compact_states)
        if args is not None:
            entity_commands.append((f"execute at {ANCHOR} run " if relative else "") + f"fill {args} strict")
    return {"S": schem_ops.decoder_blocks(), "T": enc.table, "chunks": enc.chunks,
            "ops_per_chunk": enc.ops_per_chunk, "E": entity_commands, "bytes": enc.nbytes, "stats": stats,
            "restore": restore}


