def _compact_float(x: float) -> str:
    """Shortest ordinary decimal that is valid as an SNBT float literal."""
    if abs(x) < 5e-10:
        x = 0.0
    if float(x).is_integer():
        return f"{int(x)}f"
    text = f"{x:.6f}".rstrip("0").rstrip(".")
    if text.startswith("-0."):
        text = "-." + text[3:]
    elif text.startswith("0."):
        text = "." + text[2:]
    return text + "f"


def _coord_2d(x: int, z: int, relative: bool) -> str:
    if relative:
        return f"{fmt_rel(x)} {fmt_rel(z)}"
    return f"{x} {z}"



def _max_chunks_for_block_span(block_count: int) -> int:
    """Worst-case chunks touched by N consecutive blocks with unknown chunk alignment."""
    if block_count <= 0:
        return 0
    return (block_count + 30) // 16  # ceil((N + 15) / 16)


def _safe_forceload_segments(start: int, block_count: int, capacity_chunks: int) -> List[Tuple[int, int]]:
    # To guarantee <= capacity_chunks regardless of the command source's position
    # within its current chunk, a segment can contain at most 16*C - 15 blocks.
    max_blocks = max(1, 16 * capacity_chunks - 15)
    count = (block_count + max_blocks - 1) // max_blocks
    return _segments(start, block_count, count)


def forceload_commands(schem: Schematic, origin: Tuple[int, int, int], relative: bool) -> List[str]:
    """Return /forceload add commands covering the full schematic footprint.

    A single Java /forceload add may cover at most 256 chunks. Relative output cannot
    know the eventual world-coordinate alignment, so the tiling below uses worst-case
    chunk alignment and is therefore safe wherever the command list is executed.
    """
    x0, z0 = origin[0], origin[2]
    w, l = schem.width, schem.length

    # Find chunk capacities (cx, cz) with cx*cz <= 256 that minimize command count.
    best = None
    for cx in range(1, 257):
        cz = 256 // cx
        max_x_blocks = 16 * cx - 15
        max_z_blocks = 16 * cz - 15
        nx = (w + max_x_blocks - 1) // max_x_blocks
        nz = (l + max_z_blocks - 1) // max_z_blocks
        metric = (nx * nz, nx + nz, -cx * cz)
        if best is None or metric < best[0]:
            best = (metric, cx, cz)
    assert best is not None
    _, cx, cz = best

    xs = _safe_forceload_segments(x0, w, cx)
    zs = _safe_forceload_segments(z0, l, cz)
    out: List[str] = []
    for xa, xb in xs:
        for za, zb in zs:
            p1 = _coord_2d(xa, za, relative)
            p2 = _coord_2d(xb, zb, relative)
            if xa == xb and za == zb:
                out.append(f"forceload add {p1}")
            else:
                out.append(f"forceload add {p1} {p2}")
    return out


