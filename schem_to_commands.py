# ----------------------------- NBT reader/model -----------------------------

@dataclass(frozen=True)
class NBTValue:
    tag: int
    value: Any

TAG_END = 0
TAG_BYTE = 1
TAG_SHORT = 2
TAG_INT = 3
TAG_LONG = 4
TAG_FLOAT = 5
TAG_DOUBLE = 6
TAG_BYTE_ARRAY = 7
TAG_STRING = 8
TAG_LIST = 9
TAG_COMPOUND = 10
TAG_INT_ARRAY = 11
TAG_LONG_ARRAY = 12

TAG_NAMES = {
    0: "End", 1: "Byte", 2: "Short", 3: "Int", 4: "Long", 5: "Float",
    6: "Double", 7: "ByteArray", 8: "String", 9: "List", 10: "Compound",
    11: "IntArray", 12: "LongArray",
}

class NBTError(ValueError):
    pass


@dataclass(frozen=True)
class SchematicHeader:
    kind: str
    label: str
    supported: bool
    version: Optional[int] = None
    width: Optional[int] = None
    height: Optional[int] = None
    length: Optional[int] = None

    @property
    def dimensions(self) -> Optional[Tuple[int, int, int]]:
        if self.width is None or self.height is None or self.length is None:
            return None
        return self.width, self.height, self.length


class _NBTScanReader:
    """Small streaming NBT reader used only for fast format/dimension detection.

    Unlike the full NBT parser, this can skip giant block-data arrays without first
    materialising or varint-decoding them. That lets the type/dimensions and large-
    schematic warning appear before the expensive conversion work starts.
    """
    def __init__(self, f: BinaryIO):
        self.f = f

    def read_exact(self, n: int) -> bytes:
        b = self.f.read(n)
        if len(b) != n:
            raise NBTError(f"Unexpected end of NBT while inspecting header (wanted {n} bytes, got {len(b)})")
        return b

    def u8(self) -> int:
        return struct.unpack(">B", self.read_exact(1))[0]

    def i8(self) -> int:
        return struct.unpack(">b", self.read_exact(1))[0]

    def i16(self) -> int:
        return struct.unpack(">h", self.read_exact(2))[0]

    def u16(self) -> int:
        return struct.unpack(">H", self.read_exact(2))[0]

    def i32(self) -> int:
        return struct.unpack(">i", self.read_exact(4))[0]

    def i64(self) -> int:
        return struct.unpack(">q", self.read_exact(8))[0]

    def string(self) -> str:
        n = self.u16()
        return self.read_exact(n).decode("utf-8", errors="replace")

    def discard(self, n: int) -> None:
        # GzipFile relative seeks still have to decompress data, but avoid creating a
        # huge Python list/bytes copy. Chunked reads are more portable for other streams.
        while n > 0:
            chunk = self.f.read(min(n, 1024 * 1024))
            if not chunk:
                raise NBTError("Unexpected end of NBT while skipping payload")
            n -= len(chunk)


def _scan_integer(r: _NBTScanReader, tag: int) -> int:
    if tag == TAG_BYTE:
        return r.i8()
    if tag == TAG_SHORT:
        return r.i16()
    if tag == TAG_INT:
        return r.i32()
    if tag == TAG_LONG:
        return r.i64()
    raise NBTError(f"Expected integer NBT tag while inspecting header, got {tag}")


def _skip_nbt_payload(r: _NBTScanReader, tag: int) -> None:
    if tag == TAG_BYTE:
        r.discard(1)
    elif tag == TAG_SHORT:
        r.discard(2)
    elif tag in (TAG_INT, TAG_FLOAT):
        r.discard(4)
    elif tag in (TAG_LONG, TAG_DOUBLE):
        r.discard(8)
    elif tag == TAG_BYTE_ARRAY:
        n = r.i32()
        if n < 0:
            raise NBTError("Negative byte-array length while inspecting header")
        r.discard(n)
    elif tag == TAG_STRING:
        r.discard(r.u16())
    elif tag == TAG_LIST:
        elem_tag = r.u8()
        n = r.i32()
        if n < 0:
            raise NBTError("Negative list length while inspecting header")
        # Fixed-width primitive lists can be skipped in one operation.
        widths = {TAG_BYTE: 1, TAG_SHORT: 2, TAG_INT: 4, TAG_FLOAT: 4,
                  TAG_LONG: 8, TAG_DOUBLE: 8}
        if elem_tag in widths:
            r.discard(widths[elem_tag] * n)
        else:
            for _ in range(n):
                _skip_nbt_payload(r, elem_tag)
    elif tag == TAG_COMPOUND:
        while True:
            child_tag = r.u8()
            if child_tag == TAG_END:
                break
            _ = r.string()
            _skip_nbt_payload(r, child_tag)
    elif tag == TAG_INT_ARRAY:
        n = r.i32()
        if n < 0:
            raise NBTError("Negative int-array length while inspecting header")
        r.discard(n * 4)
    elif tag == TAG_LONG_ARRAY:
        n = r.i32()
        if n < 0:
            raise NBTError("Negative long-array length while inspecting header")
        r.discard(n * 8)
    else:
        raise NBTError(f"Unsupported NBT tag {tag} while inspecting header")


def _scan_candidate_compound(r: _NBTScanReader, *, nested: bool = False) -> Tuple[Dict[str, int], set[str], Optional[SchematicHeader]]:
    fields: Dict[str, int] = {}
    names: set[str] = set()
    target_ints = {"Version", "DataVersion", "Width", "Height", "Length"}

    while True:
        tag = r.u8()
        if tag == TAG_END:
            break
        name = r.string()
        names.add(name)

        if name == "Schematic" and tag == TAG_COMPOUND and not nested:
            nested_fields, nested_names, nested_header = _scan_candidate_compound(r, nested=True)
            names.update(nested_names)
            if nested_header is not None:
                return fields, names, nested_header
            # A nested Schematic compound without a complete Sponge header is already consumed.
            continue

        if name in target_ints and tag in (TAG_BYTE, TAG_SHORT, TAG_INT, TAG_LONG):
            fields[name] = _scan_integer(r, tag)
        else:
            _skip_nbt_payload(r, tag)

        if all(k in fields for k in ("Version", "Width", "Height", "Length")):
            version = fields["Version"]
            label = f"Sponge/WorldEdit .schem v{version}"
            return fields, names, SchematicHeader(
                kind="sponge",
                label=label,
                supported=version in (1, 2, 3),
                version=version,
                width=fields["Width"],
                height=fields["Height"],
                length=fields["Length"],
            )

    return fields, names, None


def inspect_schematic_header(path: str) -> SchematicHeader:
    """Quickly identify common schematic formats before full decoding."""
    ext = os.path.splitext(path)[1].lower()
    try:
        with gzip.open(path, "rb") as f:
            r = _NBTScanReader(f)
            root_tag = r.u8()
            if root_tag != TAG_COMPOUND:
                return SchematicHeader("unknown", f"Unknown gzip-NBT (root tag {root_tag})", False)
            root_name = r.string()
            fields, names, header = _scan_candidate_compound(r)
            if header is not None:
                return header
    except OSError as e:
        raise NBTError(f"Could not inspect gzip-compressed schematic: {e}") from e

    # Other supported formats share the same optimizer and item exporter.
    if ext == ".litematic" or {"Regions", "MinecraftDataVersion"}.issubset(names):
        return SchematicHeader("litematica", "Litematica .litematic", True)
    if ext == ".schematic" or {"Materials", "Blocks", "Data"}.issubset(names):
        return SchematicHeader(
            "mcedit", "Legacy MCEdit/WorldEdit .schematic", True,
            width=fields.get("Width"), height=fields.get("Height"), length=fields.get("Length")
        )
    if {"size", "palette", "blocks"}.issubset(names):
        return SchematicHeader("structure", "Vanilla structure NBT", False)
    root_desc = f" (root {root_name!r})" if root_name else ""
    return SchematicHeader("unknown", "Unknown schematic/NBT format" + root_desc, False)

class NBTReader:
    def __init__(self, data: bytes):
        self.f = io.BytesIO(data)

    def read_exact(self, n: int) -> bytes:
        b = self.f.read(n)
        if len(b) != n:
            raise NBTError(f"Unexpected end of NBT (wanted {n} bytes, got {len(b)})")
        return b

    def u8(self) -> int:
        return struct.unpack(">B", self.read_exact(1))[0]

    def i8(self) -> int:
        return struct.unpack(">b", self.read_exact(1))[0]

    def i16(self) -> int:
        return struct.unpack(">h", self.read_exact(2))[0]

    def u16(self) -> int:
        return struct.unpack(">H", self.read_exact(2))[0]

    def i32(self) -> int:
        return struct.unpack(">i", self.read_exact(4))[0]

    def i64(self) -> int:
        return struct.unpack(">q", self.read_exact(8))[0]

    def f32(self) -> float:
        return struct.unpack(">f", self.read_exact(4))[0]

    def f64(self) -> float:
        return struct.unpack(">d", self.read_exact(8))[0]

    def string(self) -> str:
        n = self.u16()
        try:
            return self.read_exact(n).decode("utf-8")
        except UnicodeDecodeError as e:
            raise NBTError(f"Invalid UTF-8 NBT string: {e}") from e

    def payload(self, tag: int) -> NBTValue:
        if tag == TAG_BYTE:
            return NBTValue(tag, self.i8())
        if tag == TAG_SHORT:
            return NBTValue(tag, self.i16())
        if tag == TAG_INT:
            return NBTValue(tag, self.i32())
        if tag == TAG_LONG:
            return NBTValue(tag, self.i64())
        if tag == TAG_FLOAT:
            return NBTValue(tag, self.f32())
        if tag == TAG_DOUBLE:
            return NBTValue(tag, self.f64())
        if tag == TAG_BYTE_ARRAY:
            n = self.i32()
            if n < 0:
                raise NBTError("Negative byte-array length")
            # Preserve signed byte semantics for SNBT.
            raw = self.read_exact(n)
            vals = [b if b < 128 else b - 256 for b in raw]
            return NBTValue(tag, vals)
        if tag == TAG_STRING:
            return NBTValue(tag, self.string())
        if tag == TAG_LIST:
            elem_tag = self.u8()
            n = self.i32()
            if n < 0:
                raise NBTError("Negative list length")
            vals = [self.payload(elem_tag) for _ in range(n)]
            return NBTValue(tag, (elem_tag, vals))
        if tag == TAG_COMPOUND:
            out: Dict[str, NBTValue] = {}
            while True:
                child_tag = self.u8()
                if child_tag == TAG_END:
                    break
                name = self.string()
                out[name] = self.payload(child_tag)
            return NBTValue(tag, out)
        if tag == TAG_INT_ARRAY:
            n = self.i32()
            if n < 0:
                raise NBTError("Negative int-array length")
            return NBTValue(tag, [self.i32() for _ in range(n)])
        if tag == TAG_LONG_ARRAY:
            n = self.i32()
            if n < 0:
                raise NBTError("Negative long-array length")
            return NBTValue(tag, [self.i64() for _ in range(n)])
        raise NBTError(f"Unsupported NBT tag {tag}")

    def read_root(self) -> Tuple[str, NBTValue]:
        tag = self.u8()
        if tag == TAG_END:
            raise NBTError("NBT root cannot be TAG_End")
        name = self.string()
        root = self.payload(tag)
        return name, root


def compound(v: NBTValue, label: str) -> Dict[str, NBTValue]:
    if v.tag != TAG_COMPOUND:
        raise NBTError(f"{label} must be a compound, got {TAG_NAMES.get(v.tag, v.tag)}")
    return v.value


def int_value(v: Optional[NBTValue], label: str) -> int:
    if v is None or v.tag not in (TAG_BYTE, TAG_SHORT, TAG_INT, TAG_LONG):
        raise NBTError(f"{label} must be an integer tag")
    return int(v.value)


def string_value(v: Optional[NBTValue], label: str) -> str:
    if v is None or v.tag != TAG_STRING:
        raise NBTError(f"{label} must be a string tag")
    return str(v.value)


def numeric_list(v: Optional[NBTValue], label: str) -> List[int]:
    if v is None:
        raise NBTError(f"Missing {label}")
    if v.tag == TAG_INT_ARRAY:
        return [int(x) for x in v.value]
    if v.tag == TAG_LIST:
        _, vals = v.value
        out = []
        for item in vals:
            if item.tag not in (TAG_BYTE, TAG_SHORT, TAG_INT, TAG_LONG):
                raise NBTError(f"{label} contains non-integer item")
            out.append(int(item.value))
        return out
    raise NBTError(f"{label} must be an int array or integer list")


def snbt_float(x: float, suffix: str) -> str:
    if math.isnan(x):
        return "NaN" + suffix
    if math.isinf(x):
        return ("-Infinity" if x < 0 else "Infinity") + suffix
    # repr gives a round-trippable representation; ensure integral-looking floats stay floats.
    s = repr(float(x))
    if "e" not in s.lower() and "." not in s:
        s += ".0"
    return s + suffix



# Characters accepted by Minecraft's unquoted SNBT token reader.
# A colon is intentionally excluded, so values such as minecraft:stone remain quoted.
_SNBT_BARE_RE = re.compile(r"^[A-Za-z0-9._+\-]+$")

def snbt_key(key: str) -> str:
    return key if _SNBT_BARE_RE.fullmatch(key) else json.dumps(key, ensure_ascii=False)

def to_snbt(v: NBTValue) -> str:
    t, x = v.tag, v.value
    if t == TAG_BYTE:
        return f"{x}b"
    if t == TAG_SHORT:
        return f"{x}s"
    if t == TAG_INT:
        return str(x)
    if t == TAG_LONG:
        return f"{x}L"
    if t == TAG_FLOAT:
        return snbt_float(x, "f")
    if t == TAG_DOUBLE:
        return snbt_float(x, "d")
    if t == TAG_STRING:
        return json.dumps(x, ensure_ascii=False)
    if t == TAG_BYTE_ARRAY:
        return "[B;" + ",".join(f"{n}b" for n in x) + "]"
    if t == TAG_INT_ARRAY:
        return "[I;" + ",".join(str(n) for n in x) + "]"
    if t == TAG_LONG_ARRAY:
        return "[L;" + ",".join(f"{n}L" for n in x) + "]"
    if t == TAG_LIST:
        _, vals = x
        return "[" + ",".join(to_snbt(item) for item in vals) + "]"
    if t == TAG_COMPOUND:
        # SNBT compound keys may be bare when they only use reader-safe characters.
        # Quote only unusual keys; this keeps common vanilla NBT substantially smaller.
        return "{" + ",".join(snbt_key(k) + ":" + to_snbt(val) for k, val in x.items()) + "}"
    raise NBTError(f"Cannot serialize NBT tag {t} to SNBT")

