def _compact_float(x: float) -> str:
    """Shortest ordinary decimal that is valid as an SNBT float literal."""
    if abs(x) < 5e-10:
        x = 0.0
    if float(x).is_integer():
        return f"{int(x)}f"
    text = f"{x:.6f}".rstrip("0").rstrip(".")
    if text.startswith("-0."):
        text = "-." + text[3:]
    elif text.startswith("0."):
        text = "." + text[2:]
    return text + "f"


def _coord_2d(x: int, z: int, relative: bool) -> str:
    if relative:
        return f"{fmt_rel(x)} {fmt_rel(z)}"
    return f"{x} {z}"



def _max_chunks_for_block_span(block_count: int) -> int:
    """Worst-case chunks touched by N consecutive blocks with unknown chunk alignment."""
    if block_count <= 0:
        return 0
    return (block_count + 30) // 16  # ceil((N + 15) / 16)


def _safe_forceload_segments(start: int, block_count: int, capacity_chunks: int) -> List[Tuple[int, int]]:
    max_blocks = max(1, 16 * capacity_chunks - 15)
    count = (block_count + max_blocks - 1) // max_blocks
    return _segments(start, block_count, count)


def forceload_commands(schem: Schematic, origin: Tuple[int, int, int], relative: bool) -> List[str]:
    """Return /forceload add commands covering the full schematic footprint.

    A single Java /forceload add may cover at most 256 chunks. Relative output cannot
    know the eventual world-coordinate alignment, so the tiling below uses worst-case
    chunk alignment and is therefore safe wherever the command list is executed.
    """
    x0, z0 = origin[0], origin[2]
    w, l = schem.width, schem.length

    best = None
    for cx in range(1, 257):
        cz = 256 // cx
        max_x_blocks = 16 * cx - 15
        max_z_blocks = 16 * cz - 15
        nx = (w + max_x_blocks - 1) // max_x_blocks
        nz = (l + max_z_blocks - 1) // max_z_blocks
        metric = (nx * nz, nx + nz, -cx * cz)
        if best is None or metric < best[0]:
            best = (metric, cx, cz)
    assert best is not None
    _, cx, cz = best

    xs = _safe_forceload_segments(x0, w, cx)
    zs = _safe_forceload_segments(z0, l, cz)
    out: List[str] = []
    for xa, xb in xs:
        for za, zb in zs:
            p1 = _coord_2d(xa, za, relative)
            p2 = _coord_2d(xb, zb, relative)
            if xa == xb and za == zb:
                out.append(f"forceload add {p1}")
            else:
                out.append(f"forceload add {p1} {p2}")
    return out


def _short_resource_location(value: str) -> str:
    return value[10:] if value.startswith("minecraft:") else value


def _bounding_box_display_parts(schem: Schematic, block: str = "red_stained_glass",
                                thickness: float = 0.15, tag: str = "schem_bbox",
                                glow_color_override: int = 16737792,
                                translation_base: Tuple[int, int, int] = (0, 0, 0)) -> Tuple[List[str], str]:
    """Return transformation-only display passengers and their shared NBT.

    Each passenger stores only the edge-specific transformation. All identical
    display data is returned separately so an ``execute ... on passengers``
    command can apply it once to every direct passenger of the base entity.
    """
    if thickness <= 0:
        raise ValueError("bounding-box thickness must be > 0")

    w, h, l = schem.width, schem.height, schem.length
    t = float(thickness)
    half = t / 2.0
    edges: List[Tuple[Tuple[int, int, int], Tuple[float, float, float], Tuple[float, float, float]]] = []

    for y in (0, h):
        for z in (0, l):
            edges.append(((0, y, z), (0.0, -half, -half), (float(w), t, t)))
    for x in (0, w):
        for z in (0, l):
            edges.append(((x, 0, z), (-half, 0.0, -half), (t, float(h), t)))
    for x in (0, w):
        for y in (0, h):
            edges.append(((x, y, 0), (-half, -half, 0.0), (t, t, float(l))))

    passengers: List[str] = []
    for local_pos, offset, scale in edges:
        translation = tuple(
            float(translation_base[i] + local_pos[i]) + offset[i] + (BORDER_Y_OFFSET if i == 1 else 0.0)
            for i in range(3)
        )
        tx, ty, tz = translation
        sx, sy, sz = scale
        matrix = (
            sx, 0.0, 0.0, tx,
            0.0, sy, 0.0, ty,
            0.0, 0.0, sz, tz,
            0.0, 0.0, 0.0, 1.0,
        )
        mat = ",".join(_compact_float(v) for v in matrix)
        passengers.append(
            '{id:"block_display",transformation:[' + mat + ']}'
        )

    block_id = _short_resource_location(block)
    safe_tag = re.sub(r"[^A-Za-z0-9_.+\-]", "_", tag) or "schem_bbox"
    shared = (
        '{brightness:{block:15,sky:15},Tags:[' + json.dumps(safe_tag) + '],'
        'block_state:{Name:' + json.dumps(block_id) + ',id:' + json.dumps(block_id) + '},Glowing:1b,'
        'glow_color_override:' + str(int(glow_color_override)) + '}'
    )
    return passengers, shared



def _forceload_chunk_count(schem: Schematic, origin: Tuple[int, int, int], relative: bool) -> int:
    """Chunks touched by the schematic footprint (worst-case for relative placement)."""
    x0, z0 = origin[0], origin[2]
    x1, z1 = x0 + schem.width - 1, z0 + schem.length - 1
    if relative:
        return _max_chunks_for_block_span(schem.width) * _max_chunks_for_block_span(schem.length)
    return (x1 // 16 - x0 // 16 + 1) * (z1 // 16 - z0 // 16 + 1)


def _forceload_arguments(schem: Schematic, origin: Tuple[int, int, int], relative: bool) -> List[str]:
    """Return one or more legal <=256-chunk from/to argument rectangles."""
    cmds = forceload_commands(schem, origin, relative)
    prefix = "forceload add "
    return [cmd[len(prefix):] if cmd.startswith(prefix) else cmd for cmd in cmds]


def _cleanup_path(count: int) -> List[Tuple[int, int, int]]:
    """Create an adjacent serpentine command-block path for loader cleanup.

    It starts at the template's fixed cleanup trigger block (28800024,176,28800002)
    and expands through Y/Z first, then +X. This keeps every command block adjacent so
    a normal chain can execute arbitrary numbers of matching forceload removals.
    """
    if count <= 0:
        return []
    y0, y1 = 176, 319
    z0, z1 = 28800002, 28800007
    per_x = (y1 - y0 + 1) * (z1 - z0 + 1)
    max_x_layers = MAX_BLOCK_MODIFICATIONS // ((y1 - y0 + 1) * (z1 - z0 + 1))
    if count > per_x * max_x_layers:
        raise ValueError(
            f"loader cleanup needs {count} command blocks, exceeding the safe staging capacity "
            f"of {per_x * max_x_layers}; split the schematic"
        )

    out: List[Tuple[int, int, int]] = []
    x = 28800024
    while len(out) < count:
        layer = x - 28800024
        z_values = list(range(z0, z1 + 1))
        if layer % 2:
            z_values.reverse()
        for zi, z in enumerate(z_values):
            upward = ((zi + layer) % 2 == 0)
            ys = range(y0, y1 + 1) if upward else range(y1, y0 - 1, -1)
            for y in ys:
                out.append((x, y, z))
                if len(out) >= count:
                    return out
        x += 1
    return out


def _facing_between(a: Tuple[int, int, int], b: Tuple[int, int, int]) -> str:
    dx, dy, dz = b[0]-a[0], b[1]-a[1], b[2]-a[2]
    lookup = {(1,0,0):"east",(-1,0,0):"west",(0,1,0):"up",(0,-1,0):"down",(0,0,1):"south",(0,0,-1):"north"}
    try:
        return lookup[(dx,dy,dz)]
    except KeyError as e:
        raise ValueError(f"non-adjacent cleanup path step: {a} -> {b}") from e


