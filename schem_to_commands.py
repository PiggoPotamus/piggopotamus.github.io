def _bounding_box_display_parts(schem: Schematic, block: str = "red_stained_glass",
                                thickness: float = 0.15, tag: str = "schem_bbox",
                                glow_color_override: int = 16737792,
                                translation_base: Tuple[int, int, int] = (0, 0, 0)) -> Tuple[List[str], str]:
    """Return transformation-only display passengers and their shared NBT.

    Each passenger stores only the edge-specific transformation. All identical
    display data is returned separately so an ``execute ... on passengers``
    command can apply it once to every direct passenger of the base entity.
    """
    if thickness <= 0:
        raise ValueError("bounding-box thickness must be > 0")

    w, h, l = schem.width, schem.height, schem.length
    t = float(thickness)
    half = t / 2.0
    edges: List[Tuple[Tuple[int, int, int], Tuple[float, float, float], Tuple[float, float, float]]] = []

    for y in (0, h):
        for z in (0, l):
            edges.append(((0, y, z), (0.0, -half, -half), (float(w), t, t)))
    for x in (0, w):
        for z in (0, l):
            edges.append(((x, 0, z), (-half, 0.0, -half), (t, float(h), t)))
    for x in (0, w):
        for y in (0, h):
            edges.append(((x, y, 0), (-half, -half, 0.0), (t, t, float(l))))

    passengers: List[str] = []
    for local_pos, offset, scale in edges:
        translation = tuple(
            float(translation_base[i] + local_pos[i]) + offset[i] + (BORDER_Y_OFFSET if i == 1 else 0.0)
            for i in range(3)
        )
        tx, ty, tz = translation
        sx, sy, sz = scale
        # Display entities accept the transformation as a complete 4x4 matrix.
        # Using the matrix form is shorter than spelling out translation, scale,
        # left_rotation and right_rotation, while still explicitly defining the
        # entire transform (important because omitted compound fields use defaults).
        # Minecraft accepts the 16-number form as a row-major affine matrix:
        # diagonal = scale and the final column = translation.
        matrix = (
            sx, 0.0, 0.0, tx,
            0.0, sy, 0.0, ty,
            0.0, 0.0, sz, tz,
            0.0, 0.0, 0.0, 1.0,
        )
        mat = ",".join(_compact_float(v) for v in matrix)
        passengers.append(
            '{id:"block_display",transformation:[' + mat + ']}'
        )

    block_id = _short_resource_location(block)
    safe_tag = re.sub(r"[^A-Za-z0-9_.+\-]", "_", tag) or "schem_bbox"
    shared = (
        '{brightness:{block:15,sky:15},Tags:[' + json.dumps(safe_tag) + '],'
        'block_state:{Name:' + json.dumps(block_id) + '},Glowing:1b,'
        'glow_color_override:' + str(int(glow_color_override)) + '}'
    )
    return passengers, shared



def _forceload_chunk_count(schem: Schematic, origin: Tuple[int, int, int], relative: bool) -> int:
    """Chunks touched by the schematic footprint (worst-case for relative placement)."""
    x0, z0 = origin[0], origin[2]
    x1, z1 = x0 + schem.width - 1, z0 + schem.length - 1
    if relative:
        return _max_chunks_for_block_span(schem.width) * _max_chunks_for_block_span(schem.length)
    return (x1 // 16 - x0 // 16 + 1) * (z1 // 16 - z0 // 16 + 1)


def _forceload_arguments(schem: Schematic, origin: Tuple[int, int, int], relative: bool) -> List[str]:
    """Return one or more legal <=256-chunk from/to argument rectangles."""
    cmds = forceload_commands(schem, origin, relative)
    prefix = "forceload add "
    return [cmd[len(prefix):] if cmd.startswith(prefix) else cmd for cmd in cmds]


def _cleanup_path(count: int) -> List[Tuple[int, int, int]]:
    """Create an adjacent serpentine command-block path for loader cleanup.

    It starts at the template's fixed cleanup trigger block (28800024,176,28800002)
    and expands through Y/Z first, then +X. This keeps every command block adjacent so
    a normal chain can execute arbitrary numbers of matching forceload removals.
    """
    if count <= 0:
        return []
    y0, y1 = 176, 319
    z0, z1 = 28800002, 28800007
    per_x = (y1 - y0 + 1) * (z1 - z0 + 1)
    # The loader raises max_block_modifications before building this staging area,
    # so the final self-clear may use the same configured 9,999,999-block limit.
    # The generated item becomes impractically large long before this capacity in
    # normal use, but keeping the limits aligned avoids an artificial 32,768 cap.
    max_x_layers = MAX_BLOCK_MODIFICATIONS // ((y1 - y0 + 1) * (z1 - z0 + 1))
    if count > per_x * max_x_layers:
        raise ValueError(
            f"loader cleanup needs {count} command blocks, exceeding the safe staging capacity "
            f"of {per_x * max_x_layers}; split the schematic"
        )

    out: List[Tuple[int, int, int]] = []
    x = 28800024
    while len(out) < count:
        layer = x - 28800024
        z_values = list(range(z0, z1 + 1))
        if layer % 2:
            z_values.reverse()
        for zi, z in enumerate(z_values):
            # Alternate vertical direction per column. The layer parity is included
            # so the end of one X layer is adjacent to the start of the next.
            upward = ((zi + layer) % 2 == 0)
            ys = range(y0, y1 + 1) if upward else range(y1, y0 - 1, -1)
            for y in ys:
                out.append((x, y, z))
                if len(out) >= count:
                    return out
        x += 1
    return out


def _facing_between(a: Tuple[int, int, int], b: Tuple[int, int, int]) -> str:
    dx, dy, dz = b[0]-a[0], b[1]-a[1], b[2]-a[2]
    lookup = {(1,0,0):"east",(-1,0,0):"west",(0,1,0):"up",(0,-1,0):"down",(0,0,1):"south",(0,0,-1):"north"}
    try:
        return lookup[(dx,dy,dz)]
    except KeyError as e:
        raise ValueError(f"non-adjacent cleanup path step: {a} -> {b}") from e


def _cleanup_minecart_lines(remove_args: Sequence[str]) -> Tuple[List[str], Tuple[int,int,int,int,int,int]]:
    """Build the cleanup command-block chain and return its staging bounds."""
    commands: List[str] = [
        'data merge block 28800024 176 28800002 {auto:0b}',
        r'execute if score #m p2 matches 1.. run title @a[scores={p2=1..}] actionbar {\\"text\\":\\"Schematic complete\\",\\"color\\":\\"green\\"}',
        r'execute if score #m p2 matches 1.. run tellraw @a[scores={p2=1..}] {\\"color\\":\\"green\\",\\"italic\\":false,\\"text\\":\\"Schematic printing complete.\\"}',
        'execute if score #m p2 matches 1.. run playsound block.note_block.pling master @a[scores={p2=1..}] ~ ~ ~ 1 1 1',
        'execute at 00014317-0001-4317-0000-58b700014317 if block ~ ~ ~ command_block run fill ~ ~ ~ ~ ~1 ~ air strict',
        'data remove storage p2:l F',
        'data remove storage p2:l D',
    ]
    commands.extend(
        'execute at 00014317-0001-4317-0000-58b700014317 run forceload remove ' + arg
        for arg in remove_args
    )
    commands.extend([
        'stopwatch remove pg.schem',
        'scoreboard objectives remove p2',
        'forceload remove 28800018 28800002',
        'kill @e[tag=p2.x]',
    ])

    # Reserve one final command block for self-clearing the whole expanded staging box.
    path = _cleanup_path(len(commands) + 1)
    xs=[p[0] for p in path]; ys=[p[1] for p in path]; zs=[p[2] for p in path]
    bounds=(28800018,176,28800002,max(max(xs),28800024),max(max(ys),188),max(max(zs),28800007))
    commands.append(f'fill {bounds[0]} {bounds[1]} {bounds[2]} {bounds[3]} {bounds[4]} {bounds[5]} air strict')

    lines: List[str] = []
    for i,(pos,cmd) in enumerate(zip(path, commands)):
        if i + 1 < len(path):
            facing = _facing_between(pos, path[i+1])
        else:
            facing = 'up'
        block = 'repeating_command_block' if i == 0 else 'chain_command_block'
        auto = '0b' if i == 0 else '1b'
        lines.append(
            f'{{id:"command_block_minecart",Command:"setblock {pos[0]} {pos[1]} {pos[2]} {block}[facing={facing}]'
            f"{{auto:{auto},Command:\\'{cmd}\\'}}\"}},"
        )
    return lines, bounds


def _escape_nested_minecart_command(command: str) -> str:
    # This command is a double-quoted SNBT string nested inside the template's
    # outer single-quoted Command string. After the outer string is parsed, the
    # inner command must still contain \" escapes, so the source text needs two
    # literal backslashes before every inner double quote.
    return command.replace("\\", "\\\\").replace('"', r'\\"')


def _json_text_fragment(text: str) -> str:
    # Safe replacement for text already inside a JSON string literal.
    return json.dumps(text, ensure_ascii=False)[1:-1]


def _split_fill_entry(entry: str) -> Tuple[str, str]:
    """Return (coordinate-range, block-argument) for one fill-argument entry."""
    parts = entry.split(" ", 6)
    if len(parts) != 7:
        raise ValueError(f"malformed fill argument (expected 6 coordinates plus block): {entry!r}")
    return " ".join(parts[:6]), parts[6]


FillGroup = Tuple[str, List[str]]


def _group_fill_phase(fill_entries: Sequence[str]) -> List[FillGroup]:
    """Group a reorder-safe phase by full block argument, preserving first-seen order."""
    grouped: Dict[str, List[str]] = {}
    for entry in fill_entries:
        coords, block = _split_fill_entry(entry)
        grouped.setdefault(block, []).append(coords)
    return [(block, coords) for block, coords in grouped.items()]


def group_fill_entries(fill_entries: Sequence[str], air_clear_fills: int,
                       non_air_fills: int) -> List[FillGroup]:
    """Compact F by storing each block argument once per safe placement phase.

    Air pre-clear, ordinary non-overlapping cuboids, and block-entity restore fills
    are kept as separate phases so grouping never moves a restore ahead of the base
    placement it is supposed to overwrite. Within each phase, fills do not overlap,
    so grouping by block argument is order-safe under `fill ... strict`.
    """
    a = air_clear_fills
    b = a + non_air_fills
    if a < 0 or non_air_fills < 0 or b > len(fill_entries):
        raise ValueError("invalid fill phase counts while grouping payload")
    phases = (fill_entries[:a], fill_entries[a:b], fill_entries[b:])
    groups: List[FillGroup] = []
    for phase in phases:
        if phase:
            groups.extend(_group_fill_phase(phase))
    return groups


def _group_open_bytes(block: str) -> int:
    return len(("[" + quote_output_entry(block) + "\n").encode("utf-8"))


def _group_coord_bytes(coords: str) -> int:
    return len((quote_output_entry(coords) + "\n").encode("utf-8"))


def _group_close_bytes() -> int:
    return len("],\n".encode("utf-8"))


def render_fill_group_lines(fill_groups: Sequence[FillGroup]) -> List[str]:
    lines: List[str] = []
    for block, coords_list in fill_groups:
        lines.append("[" + quote_output_entry(block))
        lines.extend(quote_output_entry(coords) for coords in coords_list)
        lines.append("],")
    return lines


def fill_group_payload_size(fill_groups: Sequence[FillGroup]) -> int:
    close = _group_close_bytes()
    total = 0
    for block, coords_list in fill_groups:
        total += _group_open_bytes(block) + close
        total += sum(_group_coord_bytes(coords) for coords in coords_list)
    return total


def fill_group_command_count(fill_groups: Sequence[FillGroup]) -> int:
    return sum(len(coords) for _, coords in fill_groups)


def split_fill_groups(fill_groups: Sequence[FillGroup],
                      limit_bytes: int = ITEM_FILL_PAYLOAD_LIMIT_BYTES) -> List[List[FillGroup]]:
    """Split grouped F payload into contiguous item parts under the byte limit.

    A block group may be split across item files; its block argument is then repeated
    once at the start of each affected part. Coordinate order and group/phase order are
    preserved exactly.
    """
    if limit_bytes <= 0:
        raise ValueError("fill payload limit must be positive")

    parts: List[List[FillGroup]] = []
    current: List[FillGroup] = []
    current_bytes = 0
    close_bytes = _group_close_bytes()

    def flush() -> None:
        nonlocal current, current_bytes
        if current:
            parts.append(current)
            current = []
            current_bytes = 0

    for block, coords_list in fill_groups:
        open_bytes = _group_open_bytes(block)
        overhead = open_bytes + close_bytes
        if not coords_list:
            continue
        i = 0
        while i < len(coords_list):
            first_coord_bytes = _group_coord_bytes(coords_list[i])
            if overhead + first_coord_bytes > limit_bytes:
                raise ValueError(
                    f"one grouped fill entry for {block!r} needs {overhead + first_coord_bytes:,} UTF-8 bytes, "
                    f"larger than the {limit_bytes:,}-byte per-item fill-payload limit"
                )

            # Start this (possibly split) block group in the current part. If its
            # first coordinate cannot fit, close the part and retry in a new one.
            if current_bytes + overhead + first_coord_bytes > limit_bytes:
                flush()

            chunk: List[str] = []
            current.append((block, chunk))
            current_bytes += overhead

            while i < len(coords_list):
                cb = _group_coord_bytes(coords_list[i])
                if current_bytes + cb > limit_bytes:
                    break
                chunk.append(coords_list[i])
                current_bytes += cb
                i += 1

            if not chunk:
                raise AssertionError("group splitter failed to place a coordinate")
            if i < len(coords_list):
                flush()

    flush()
    if not parts:
        parts.append([])
    return parts


def _part_output_path(output: str, part_index: int, part_count: int) -> str:
    if part_count <= 1:
        return output
    root, ext = os.path.splitext(output)
    return f"{root}_part{part_index}{ext}"


def render_dynamic_item(template: str, schem: Schematic, fill_groups: Sequence[FillGroup],
                        origin: Tuple[int, int, int], relative: bool,
                        name: str, description: str, author: str, include_credit: bool,
                        bounds_block: str, bounds_thickness: float) -> str:
    """Fill the PiggoPotamus grouped-payload loader template with this schematic.

    F is emitted as nested groups: [block_argument, coord_range, coord_range, ...].
    Large footprints are split into legal forceload rectangles and the cleanup chain
    is resized/routed automatically.
    """
    forceload_args = _forceload_arguments(schem, origin, relative)
    cleanup_lines, staging = _cleanup_minecart_lines(forceload_args)
    placement_base = origin
    # Relative placement keeps the origin shift inside each display matrix because
    # the displays initially live at the loader's execution position. In absolute
    # mode the matrices stay local to the schematic and, after all destination
    # chunks have been forceloaded, the display entities themselves are teleported
    # to the final absolute placement base. This prevents the absolute origin from
    # being applied twice (entity position + transformation translation).
    bounds_translation_base = placement_base if relative else (0, 0, 0)
    bounds_passengers, bounds_shared = _bounding_box_display_parts(
        schem, block=bounds_block, thickness=bounds_thickness, tag="p2.x",
        glow_color_override=16737792, translation_base=bounds_translation_base
    )
    # Preview displays ride a dedicated block-display root. A block_display with
    # no block_state remains visually empty, but unlike a marker it supports
    # passengers. This keeps the confirmation text independent and lets absolute
    # mode teleport the entire border with one command.
    bounds_root_uuid = "00014319-0001-4319-0000-58b900014319"
    bounds_root_nbt = (
        '{UUID:[I;82713,82713,22713,82713],Tags:["p2.x"],Passengers:['
        + ','.join(bounds_passengers) + ']}'
    )
    bounds_root_summon = 'summon block_display ~ ~ ~ ' + bounds_root_nbt
    bounds_root_summon_nested = _escape_nested_minecart_command(bounds_root_summon)
    bounds_merge = (
        f"execute as {bounds_root_uuid} on passengers "
        "run data merge entity @s " + bounds_shared
    )
    bounds_merge_nested = _escape_nested_minecart_command(bounds_merge)
    bounds_teleport_nested: Optional[str] = None
    if not relative:
        bx, by, bz = placement_base
        bounds_teleport = f"tp {bounds_root_uuid} {bx} {by} {bz}"
        bounds_teleport_nested = _escape_nested_minecart_command(bounds_teleport)

    lines = template.splitlines()
    out: List[str] = []
    template_has_max_mod_rule = (
        'gamerule max_block_modifications ' in template
        or 'gamerule minecraft:max_block_modifications ' in template
    )

    # Find the outer F section, not an inner ], from one of its block groups.
    try:
        f_start = next(i for i, line in enumerate(lines) if line.strip() == "F:[")
        d_start = next(i for i in range(f_start + 1, len(lines)) if lines[i].lstrip().startswith("D:"))
        f_end = max(i for i in range(f_start + 1, d_start) if lines[i].strip() == "],")
    except (StopIteration, ValueError) as e:
        raise ValueError("item template is missing a complete grouped F:[ ... ], section before D:") from e

    in_cleanup = False
    saw_add = saw_bounds = saw_cleanup = False
    i = 0
    while i < len(lines):
        line = lines[i]

        if i == f_start:
            out.append(line)
            out.append("")
            out.extend(render_fill_group_lines(fill_groups))
            out.append("")
            out.append(lines[f_end])
            i = f_end + 1
            continue
        if f_start < i <= f_end:
            i += 1
            continue

        # Keep the loader item from starting twice at the same execution position.
        line = line.replace(
            "Command:'execute if block ~ ~1 ~ activator_rail run summon item",
            "Command:'execute unless entity @e[type=command_block_minecart,dx=0,tag=p2.xx] "
            "if block ~ ~1 ~ activator_rail run summon item"
        )

        # Ensure exactly one easily-detected loader minecart carries p2.xx, and every
        # loader item raises the per-command modification limit.
        if 'Command:"gamerule command_block_output false"' in line:
            if 'Tags:["p2.xx"]' not in line:
                line = re.sub(
                    r'(\{id:"command_block_minecart",Command:"gamerule command_block_output false")(\},?)',
                    r'\1,Tags:["p2.xx"]\2', line, count=1
                )
            out.append(line)
            if not template_has_max_mod_rule:
                out.append('{id:"command_block_minecart",Command:"gamerule max_block_modifications 9999999"},')
            i += 1
            continue

        # Replace the supplied cleanup chain wholesale, regardless of how tall the
        # template example happened to be. This is required for split forceloads.
        if 'setblock 28800024 176 28800002 repeating_command_block' in line:
            in_cleanup = True
            saw_cleanup = True
            out.extend(cleanup_lines)
            i += 1
            continue
        if in_cleanup:
            if 'fill 28800018 176 28800002 ' in line and ' air strict' in line:
                in_cleanup = False
            i += 1
            continue

        if 'execute at 00014317-0001-4317-0000-58b700014317 run forceload add ' in line:
            # The supplied example can contain many already-expanded forceload lines.
            # Replace the whole run exactly once, then skip the remaining example lines.
            if not saw_add:
                for arg in forceload_args:
                    out.append(
                        '{id:"command_block_minecart",Command:"execute at '
                        '00014317-0001-4317-0000-58b700014317 run forceload add ' + arg + '"},'
                    )
                # Absolute previews must be moved only after every destination chunk
                # has been forceloaded. The text display remains at the loader, while
                # its 12 block-display passengers are moved to the final world origin.
                if bounds_teleport_nested is not None:
                    out.append('{id:"command_block_minecart",Command:"' + bounds_teleport_nested + '"},')
                saw_add = True
            i += 1
            continue
        if 'summon text_display' in line and 'UUID:[I;82711,82711,22711,82711]' in line:
            # The confirmation text is independent from the border root. Strip any
            # legacy preview Passengers list from older templates.
            marker = 'Passengers:['
            if marker in line:
                marker_at = line.index(marker)
                start_p = marker_at + len(marker)
                depth = 1
                j = start_p
                while j < len(line) and depth:
                    if line[j] == '[':
                        depth += 1
                    elif line[j] == ']':
                        depth -= 1
                    j += 1
                if depth:
                    raise ValueError("unterminated Passengers list in template text_display")
                # Remove the preceding comma too when present.
                cut = marker_at - 1 if marker_at > 0 and line[marker_at - 1] == ',' else marker_at
                line = line[:cut] + line[j:]
            if not relative:
                bx, by, bz = placement_base
                confirm = f"Confirm/Cancel placement at {bx} {by} {bz}"
                line = re.sub(
                    r'Confirm/Cancel placement(?: at -?\d+ -?\d+ -?\d+)?:',
                    confirm, line, count=1
                )
                # Older/current template text ends with a colon. Also handle exact escaped literal.
                line = line.replace('Confirm/Cancel placement:', confirm)
            out.append(line)
            out.append('{id:"command_block_minecart",Command:"' + bounds_root_summon_nested + '"},')
            out.append('{id:"command_block_minecart",Command:"' + bounds_merge_nested + '"},')
            saw_bounds = True
            i += 1
            continue

        # Discard legacy preview roots/merges from older templates; the generated
        # dedicated block-display root and relation-based merge above replace them.
        if (('run summon block_display' in line or 'run summon marker' in line) and 'Passengers:' in line):
            i += 1
            continue
        if ('as @e[type=minecraft:block_display,dx=0] run data merge entity @s' in line
                or 'on passengers run data merge entity @s' in line):
            i += 1
            continue

        # If the confirmation text is destroyed, immediately activate cleanup.
        # Insert this watcher before the control column's final minecart-kill block
        # and move that final block up by one Y so the chain remains contiguous.
        if ('setblock 28800023 185 28800002 chain_command_block' in line
                and 'kill @e[type=command_block_minecart,distance=..3]' in line):
            watcher_cmd = (
                'execute unless entity 00014317-0001-4317-0000-58b700014317 '
                'run data merge block 28800024 176 28800002 {auto:1b}'
            )
            watcher = (
                "{id:\"command_block_minecart\",Command:\"setblock 28800023 185 28800002 "
                "chain_command_block[facing=up]{auto:1b,Command:\\'" + watcher_cmd + "\\'}\"},"
            )
            out.append(watcher)
            line = line.replace('setblock 28800023 185 28800002',
                                'setblock 28800023 186 28800002', 1)

        # Rewrite item lore from current schematic metadata/CLI values. This also
        # replaces the legacy "Created by PiggoPotamus" line in older templates.
        if 'lore=[' in line and '],enchantment_glint_override' in line:
            start = line.index('lore=[') + len('lore=[')
            end = line.index('],enchantment_glint_override', start)
            desc_component = '{"color":"gray","italic":false,"text":' + json.dumps(description, ensure_ascii=False) + '}'
            author_component = ('[{"color":"dark_gray","italic":false,"text":"Schem author: "},'
                                '{"color":"aqua","italic":false,"text":' + json.dumps(author, ensure_ascii=False) + '}]')
            lore_parts = [desc_component, author_component]
            if not relative:
                bx, by, bz = placement_base
                origin_component = (
                    '[{"color":"dark_gray","italic":false,"text":"Origin: "},'
                    '{"color":"yellow","italic":false,"text":'
                    + json.dumps(f"{bx} {by} {bz}", ensure_ascii=False) + '}]'
                )
                lore_parts.append(origin_component)
            if include_credit:
                lore_parts.append('{"color":"red","italic":false,"text":' +
                                  json.dumps(VISIBLE_GENERATOR_CREDIT, ensure_ascii=False) + '}')
            line = line[:start] + ','.join(lore_parts) + line[end:]

        # Permanent machine-readable provenance. Remove legacy Piggo marker fields;
        # --no-credit affects only visible lore, never this attribution.
        if 'custom_data={' in line and (
                'pg.schemloader' in line or 'GeneratedByPiggoSchemConverter:' in line
                or 'MadeByPiggo' in line or 'PiggoPotamus:1b' in line):
            line = re.sub(r'(?<![A-Za-z0-9_.-])MadeByPiggo:1b,?', '', line)
            line = re.sub(r'(?<![A-Za-z0-9_.-])author:"PiggoPotamus",?', '', line)
            line = re.sub(r'(?<![A-Za-z0-9_.-])PiggoPotamus:1b,?', '', line)
            # Clean accidental doubled commas after removing fields.
            line = line.replace('custom_data={,', 'custom_data={')
            while ',,' in line:
                line = line.replace(',,', ',')
            if 'GeneratedByPiggoSchemConverter:' not in line:
                marker = 'custom_data={'
                at = line.index(marker) + len(marker)
                entry = ('GeneratedByPiggoSchemConverter:' +
                         json.dumps(PERMANENT_GENERATOR_ATTRIBUTION, ensure_ascii=False) + ',')
                line = line[:at] + entry + line[at:]

        # The example template's staging height changes as its cleanup chain changes.
        # Match the whole staging-clear shape rather than a hard-coded Y coordinate.
        if 'Command:"fill 28800018 176 28800002 28800024 ' in line and ' 28800007 air strict"' in line:
            replacement = (
                f'fill {staging[0]} {staging[1]} {staging[2]} '
                f'{staging[3]} {staging[4]} {staging[5]} air strict'
            )
            line = re.sub(
                r'fill 28800018 176 28800002 28800024 -?\d+ 28800007 air strict',
                replacement, line, count=1
            )

        out.append(line)
        i += 1

    if in_cleanup:
        raise ValueError("item template cleanup section was not terminated as expected")
    if not saw_add:
        raise ValueError("item template is missing the schematic forceload-add placeholder")
    if not saw_bounds:
        raise ValueError("item template is missing the schematic block-display placeholder")
    if not saw_cleanup:
        raise ValueError("item template is missing the cleanup command-block chain")

    text = "\n".join(out)
    text = text.replace("<NAME>", _json_text_fragment(name))
    text = text.replace("<DESCRIPTION>", _json_text_fragment(description))
    if not text.endswith("\n"):
        text += "\n"
    return text


def generate_commands(schem: Schematic, include_air: bool, max_fill_volume: int,
                      origin: Tuple[int, int, int], relative: bool,
                      compact_states: bool = True,
                      progress: Optional[Callable[[str], None]] = None) -> Tuple[List[str], Dict[str, Any]]:
    # Air inclusion is handled as a fast pre-clear, not as part of the voxel
    # partitioner. This guarantees the output clears the whole schematic volume
    # first and then places only non-air blocks, which is dramatically smaller
    # for sparse/irregular schematics.
    if include_air and progress:
        progress("Include-air: preparing whole-volume air pre-clear...")
    cuboids, order = optimize(schem, False, max_fill_volume, progress=progress)
    air_clear_cuboids: List[Cuboid] = []
    if include_air:
        regions = schem.selected_regions or [(0, 0, 0, schem.width - 1, schem.height - 1, schem.length - 1)]
        for region in regions:
            air_clear_cuboids.extend(split_cuboid(Cuboid("minecraft:air", *region), max_fill_volume))
        if progress:
            progress(f"Include-air: whole volume will be cleared first using {len(air_clear_cuboids):,} fill command(s)")

    commands: List[str] = []

    # Clear before placing anything. The air clear itself is split only when the
    # schematic volume exceeds the configured max-block-modifications/fill limit.
    for c in air_clear_cuboids:
        commands.append(fill_args_for_cuboid(c, origin, relative, compact_states))

    if progress:
        progress(f"Serializing {len(cuboids):,} optimized non-air fill regions...")
    serialize_checkpoint = 25
    for i, c in enumerate(cuboids, 1):
        commands.append(fill_args_for_cuboid(c, origin, relative, compact_states))
        if progress and cuboids and i * 100 >= len(cuboids) * serialize_checkpoint:
            progress(f"Fill serialization: {min(100, serialize_checkpoint)}%")
            serialize_checkpoint += 25

    be_commands = 0
    for be in schem.block_entities:
        x, y, z = be.pos
        if not (0 <= x < schem.width and 0 <= y < schem.height and 0 <= z < schem.length):
            raise NBTError(f"Block entity {be.entity_id} has out-of-bounds Pos {be.pos}")
        state = schem.block_at(x, y, z)
        be_command = fill_args_for_block_entity(
            be, state, origin, relative, compact_states
        )
        if be_command is not None:
            commands.append(be_command)
            be_commands += 1

    selected_blocks = sum(1 for b in schem.blocks if b != "__unselected__" and (include_air or b not in AIR_STATES))
    stats = {
        "dimensions": (schem.width, schem.height, schem.length),
        "volume": schem.width * schem.height * schem.length,
        "selected_blocks": selected_blocks,
        "base_commands": len(air_clear_cuboids) + len(cuboids),
        "fills": len(air_clear_cuboids) + len(cuboids),
        "air_clear_fills": len(air_clear_cuboids),
        "non_air_fills": len(cuboids),
        "block_entity_fills": be_commands,
        "total_commands": len(commands),
        "axis_order": "".join("XYZ"[i] for i in order),
        "schematic_version": schem.version,
        "data_version": schem.data_version,
    }
    return commands, stats


def main(argv: Optional[Sequence[str]] = None) -> int:
    ap = argparse.ArgumentParser(
        description="Convert Sponge/WorldEdit .schem into an optimized dynamic schematic-loader item.")
    ap.add_argument("input", nargs="?", help="Input .schem, .litematic or .schematic file, or a folder when using --bulk")
    ap.add_argument("output", nargs="?", help="Output .txt (default: <input>_item.txt)")
    ap.add_argument("--bulk", action="store_true",
                    help="Process every supported schematic file in the current folder, or in the folder given as input")
    ap.add_argument("--include-air", action="store_true",
                    help="Include air/cave_air/void_air so the paste also clears existing blocks")
    ap.add_argument("--origin", nargs=3, metavar=("X", "Y", "Z"), default=(0, 0, 0), type=int,
                    help="Shift fills, forceloads, and border preview by this origin; schematic Offset metadata is ignored (default: 0 0 0)")
    ap.add_argument("--absolute", action="store_true",
                    help="Use absolute coordinates; border displays are teleported to the final absolute placement base after forceloading")
    ap.add_argument("--max-fill-volume", type=int, default=MAX_BLOCK_MODIFICATIONS,
                    help=f"Maximum blocks in one fill; 0 = unlimited (default: {MAX_BLOCK_MODIFICATIONS})")
    ap.add_argument("--keep-all-states", action="store_true",
                    help="Do not strip known default block-state properties or minecraft: namespaces")
    ap.add_argument("--bounds-block", default="red_stained_glass",
                    help="Block shown by bounding-box displays (default: red_stained_glass)")
    ap.add_argument("--bounds-thickness", type=float, default=0.15,
                    help="Bounding-box edge thickness in blocks (default: 0.15)")
    ap.add_argument("--name", help="Item display name (default: schematic filename)")
    ap.add_argument("--description", help="Override the generated item lore description (default: dimensions/fill count; schematic Description metadata is ignored)")
    ap.add_argument("--author", help="Schematic author shown in lore (overrides file metadata; default: detected author or Unknown)")
    ap.add_argument("--no-credit", action="store_true",
                    help="Hide the visible converter-credit lore line (permanent custom_data attribution remains)")
    args = ap.parse_args(argv)

    if args.bulk:
        if args.output:
            ap.error("an explicit output path cannot be used with --bulk")
        folder = args.input or os.getcwd()
        if not os.path.isdir(folder):
            ap.error("with --bulk, input must be a folder (or omit it to use the current folder)")
        schem_files = sorted(
            os.path.join(folder, name)
            for name in os.listdir(folder)
            if name.lower().endswith((".schem", ".litematic", ".schematic")) and os.path.isfile(os.path.join(folder, name))
        )
        if not schem_files:
            print(f"No .schem files found in: {os.path.abspath(folder)}", file=sys.stderr, flush=True)
            return 1

        def bulk_child_argv(path: str) -> List[str]:
            child: List[str] = [path]
            if args.include_air:
                child.append("--include-air")
            if tuple(args.origin) != (0, 0, 0):
                child += ["--origin", *(str(v) for v in args.origin)]
            if args.absolute:
                child.append("--absolute")
            if args.max_fill_volume != MAX_BLOCK_MODIFICATIONS:
                child += ["--max-fill-volume", str(args.max_fill_volume)]
            if args.keep_all_states:
                child.append("--keep-all-states")
            if args.bounds_block != "red_stained_glass":
                child += ["--bounds-block", args.bounds_block]
            if args.bounds_thickness != 0.15:
                child += ["--bounds-thickness", str(args.bounds_thickness)]
            if args.name is not None:
                child += ["--name", args.name]
            if args.description is not None:
                child += ["--description", args.description]
            if args.author is not None:
                child += ["--author", args.author]
            if args.no_credit:
                child.append("--no-credit")
            return child

        print(f"Bulk mode: found {len(schem_files)} .schem file(s) in {os.path.abspath(folder)}", file=sys.stderr, flush=True)
        succeeded = 0
        failed: List[str] = []
        for i, path in enumerate(schem_files, 1):
            print(f"\n=== [{i}/{len(schem_files)}] {os.path.basename(path)} ===", file=sys.stderr, flush=True)
            rc = main(bulk_child_argv(path))
            if rc == 0:
                succeeded += 1
            else:
                failed.append(path)
        print(f"\nBulk complete: {succeeded}/{len(schem_files)} succeeded, {len(failed)} failed.")
        if failed:
            print("Failed files:")
            for path in failed:
                print(f"  {path}")
        return 0 if not failed else 2

    if not args.input:
        ap.error("input schematic file is required unless --bulk is used")

    if args.max_fill_volume < 0:
        ap.error("--max-fill-volume must be >= 0")
    if args.bounds_thickness <= 0:
        ap.error("--bounds-thickness must be > 0")

    output = args.output
    if not output:
        stem, _ = os.path.splitext(args.input)
        output = stem + "_item.txt"

    def status(message: str) -> None:
        print(message, file=sys.stderr, flush=True)

    warned_large = False
    output_files: List[str] = []
    item_parts: List[List[FillGroup]] = []
    item_fill_groups: List[FillGroup] = []
    item_payload_bytes = 0

    try:
        # This streaming inspection runs before full NBT materialisation/varint decoding,
        # so users see the file type, dimensions, and common large-schematic warning early.
        status("[1/5] Inspecting schematic type and dimensions...")
        header = inspect_schematic_header(args.input)
        status(f"Detected schematic type: {header.label}")
        if header.dimensions is not None:
            hw, hh, hl = header.dimensions
            status(f"Detected dimensions: {hw}x{hh}x{hl}")
        if not header.supported:
            raise NBTError(f"{header.label} is not supported by this converter; supported input: .schem, .litematic or .schematic")

        # Early warning uses dimensions alone whenever the placement mode makes that
        # calculation reliable before the full Offset tag has been parsed.
        early_chunks: Optional[int] = None
        if header.dimensions is not None:
            hw, _, hl = header.dimensions
            if not args.absolute:
                early_chunks = _max_chunks_for_block_span(hw) * _max_chunks_for_block_span(hl)
            else:
                ox, _, oz = tuple(args.origin)
                early_chunks = ((ox + hw - 1) // 16 - ox // 16 + 1) * ((oz + hl - 1) // 16 - oz // 16 + 1)
        if early_chunks is not None and early_chunks > 256:
            warned_large = True
            status(
                f"WARNING: schematic footprint can touch {early_chunks:,} chunks (>256). "
                "This is a very large schematic and may take a long time to process. "
                "Forceload add/remove commands will be split automatically."
            )

        status("[2/5] Fully decoding schematic...")
        schem = load_schematic(args.input, progress=lambda m: status("  " + m))
        footprint_chunks = _forceload_chunk_count(schem, tuple(args.origin), not args.absolute)
        if footprint_chunks > 256 and not warned_large:
            warned_large = True
            status(
                f"WARNING: schematic footprint touches/can touch {footprint_chunks:,} chunks (>256). "
                "This is a very large schematic and may take a long time to process. "
                "Forceload add/remove commands will be split automatically."
            )

        status("[3/5] Optimizing block volume into fill regions...")
        # The loader item has its own forceload + preview setup, so F contains only
        # optimized fill arguments plus final 1x1x1 block-entity restores.
        fills, stats = generate_commands(
            schem=schem,
            include_air=args.include_air,
            max_fill_volume=args.max_fill_volume,
            origin=tuple(args.origin),
            relative=not args.absolute,
            compact_states=not args.keep_all_states,
            progress=lambda m: status("  " + m),
        )

        status("[4/5] Measuring fill payload and preparing item output...")
        item_fill_groups = group_fill_entries(
            fills, stats["air_clear_fills"], stats["non_air_fills"]
        )
        item_payload_bytes = fill_group_payload_size(item_fill_groups)
        item_parts = split_fill_groups(item_fill_groups, ITEM_FILL_PAYLOAD_LIMIT_BYTES)
        if len(item_parts) > 1:
            status(
                f"Fill payload is {item_payload_bytes:,} UTF-8 bytes, exceeding the "
                f"{ITEM_FILL_PAYLOAD_LIMIT_BYTES:,}-byte ({ITEM_FILL_PAYLOAD_LIMIT_BYTES / 1_000_000:.2f} MB) per-item limit. "
                f"Splitting into {len(item_parts)} items."
            )
        else:
            status(
                f"Grouped fill payload: {item_payload_bytes:,} / {ITEM_FILL_PAYLOAD_LIMIT_BYTES:,} bytes "
                f"({len(item_fill_groups):,} block groups)"
            )

        template = DEFAULT_ITEM_TEMPLATE

        metadata_name = schematic_metadata_text(schem, "Name", "SchematicName")
        detected_author = schematic_author(schem)
        base_item_name = args.name or metadata_name or os.path.splitext(os.path.basename(args.input))[0]
        item_author = args.author or detected_author or "Unknown"
        if args.author:
            status(f"Using schematic author from --author: {item_author}")
        elif detected_author:
            status(f"Detected schematic author: {item_author}")
        else:
            status("Schematic author not found; using Unknown")
        base_description = args.description

        part_count = len(item_parts)
        status(f"[5/5] Rendering {part_count} dynamic loader item{'s' if part_count != 1 else ''}...")
        for part_index, part_groups in enumerate(item_parts, 1):
            part_fill_count = fill_group_command_count(part_groups)
            if part_count > 1:
                part_name = f"{base_item_name} [Part {part_index}/{part_count}]"
                if base_description:
                    part_description = (
                        f"{base_description} • Part {part_index}/{part_count} • "
                        f"{part_fill_count} of {len(fills)} fill commands"
                    )
                else:
                    part_description = (
                        f"{schem.width}x{schem.height}x{schem.length} • Part {part_index}/{part_count} • "
                        f"{part_fill_count} of {len(fills)} fill commands"
                    )
            else:
                part_name = base_item_name
                part_description = base_description or (
                    f"{schem.width}x{schem.height}x{schem.length} • {len(fills)} fill commands"
                )

            status(f"  Rendering item {part_index}/{part_count} ({part_fill_count:,} fills, {len(part_groups):,} block groups)...")
            item_text = render_dynamic_item(
                template, schem, part_groups, tuple(args.origin), not args.absolute,
                part_name, part_description, item_author,
                not args.no_credit, args.bounds_block, args.bounds_thickness
            )
            part_output = _part_output_path(output, part_index, part_count)
            output_files.append(part_output)
            with open(part_output, "w", encoding="utf-8", newline="\n") as f:
                f.write(item_text)
    except (OSError, NBTError, ValueError) as e:
        print(f"error: {e}", file=sys.stderr, flush=True)
        return 2

    d = stats["dimensions"]
    print(f"Schematic: {header.label}, DataVersion {stats['data_version']}, {d[0]}x{d[1]}x{d[2]}")
    print(f"Selected blocks: {stats['selected_blocks']} / {stats['volume']} (include air: {args.include_air})")
    print(f"Optimizer axis order: {stats['axis_order']}")
    print(f"Fill entries in F: {len(fills)}")
    if args.include_air:
        print(f"Air pre-clear fill entries: {stats['air_clear_fills']} (before all non-air placements)")
    print(f"Optimized non-air fill entries: {stats['non_air_fills']}")
    print(f"Block-entity NBT 1x1x1 fill entries: {stats['block_entity_fills']}")
    rectangles = len(_forceload_arguments(schem, tuple(args.origin), not args.absolute))
    print("Generated dynamic loader item: yes")
    print(f"Schematic footprint chunks: {footprint_chunks:,}; forceload rectangles: {rectangles:,}")
    print(f"Grouped fill payload: {item_payload_bytes:,} bytes; block groups: {len(item_fill_groups):,}; item parts: {len(item_parts)}")
    if len(item_parts) > 1:
        for i, part in enumerate(item_parts, 1):
            print(
                f"  Part {i}/{len(item_parts)}: {fill_group_command_count(part):,} fills, "
                f"{len(part):,} block groups, {fill_group_payload_size(part):,} bytes"
            )
    if schem.entity_count:
        print(f"warning: schematic contains {schem.entity_count} non-block entities; fill cannot reproduce them", file=sys.stderr)
    if len(output_files) == 1:
        print(f"Wrote: {output_files[0]}")
    else:
        print(f"Wrote {len(output_files)} item files:")
        for path in output_files:
            print(f"  {path}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
